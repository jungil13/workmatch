'use client';

import React, { useState, useEffect } from 'react';
import Link from 'next/link';
import { useRouter } from 'next/navigation';
import { Modal } from '@/components/ui/Modal';
import { Button } from '@/components/ui/Button';
import { supabase } from '@/lib/supabase/client';
import { sendNotification } from '@/lib/notifications';
import { Job, Company } from '@/types/database';
import {
  isAutoGeneratedResume,
  saveAutoGeneratedResume,
  uploadResumeFile,
} from '@/lib/services/resumeService';
import {
  UploadCloud,
  FileText,
  CheckCircle2,
  AlertCircle,
  Building2,
  Sparkles,
  Send,
  X,
  FileCheck,
  Check,
  Loader2,
  Briefcase,
} from 'lucide-react';

interface ApplyModalProps {
  job: Job & { company?: Company };
  isOpen: boolean;
  onClose: () => void;
  onSuccess?: () => void;
  matchScore?: number;
}

type ResumeChoice = 'generated' | 'saved_uploaded' | 'new_upload';

export function ApplyModal({
  job,
  isOpen,
  onClose,
  onSuccess,
  matchScore = 0,
}: ApplyModalProps) {
  const router = useRouter();
  const [user, setUser] = useState<any>(null);
  const [profileData, setProfileData] = useState<{
    profile: any;
    seekerProfile: any;
    skills: any[];
    educations: any[];
    experiences: any[];
  } | null>(null);

  // Resume lists
  const [existingResumes, setExistingResumes] = useState<any[]>([]);
  const [generatedResume, setGeneratedResume] = useState<any | null>(null);
  const [savedUploadedResumes, setSavedUploadedResumes] = useState<any[]>([]);

  // Selection states
  const [resumeChoice, setResumeChoice] = useState<ResumeChoice>('generated');
  const [selectedSavedUploadId, setSelectedSavedUploadId] = useState<string>('');
  const [uploadedFile, setUploadedFile] = useState<File | null>(null);

  // Status & Inputs
  const [coverLetter, setCoverLetter] = useState('');
  const [uploading, setUploading] = useState(false);
  const [generatingOnTheFly, setGeneratingOnTheFly] = useState(false);
  const [submitting, setSubmitting] = useState(false);
  const [errorMessage, setErrorMessage] = useState('');
  const [success, setSuccess] = useState(false);
  const [loadingResumes, setLoadingResumes] = useState(true);

  useEffect(() => {
    if (!isOpen) {
      setSuccess(false);
      setErrorMessage('');
      setUploadedFile(null);
      return;
    }

    loadUserAndResumes();
  }, [isOpen]);

  async function loadUserAndResumes() {
    setLoadingResumes(true);
    const { data: { user } } = await supabase.auth.getUser();
    if (!user) {
      setUser(null);
      setLoadingResumes(false);
      return;
    }
    setUser(user);

    // Fetch user documents & profile data in parallel
    const [docsRes, pRes, spRes, skRes, eduRes, expRes] = await Promise.all([
      supabase
        .from('documents')
        .select('*')
        .eq('user_id', user.id)
        .eq('document_type', 'resume')
        .order('uploaded_at', { ascending: false }),
      supabase.from('profiles').select('*').eq('id', user.id).maybeSingle(),
      supabase.from('job_seeker_profiles').select('*').eq('user_id', user.id).maybeSingle(),
      supabase.from('job_seeker_skills').select('*, skill:skills(*)').eq('user_id', user.id),
      supabase.from('educations').select('*').eq('user_id', user.id),
      supabase.from('work_experiences').select('*').eq('user_id', user.id),
    ]);

    setProfileData({
      profile: pRes.data || {},
      seekerProfile: spRes.data || {},
      skills: skRes.data ?? [],
      educations: eduRes.data ?? [],
      experiences: expRes.data ?? [],
    });

    const allResumes = docsRes.data ?? [];
    setExistingResumes(allResumes);

    // Filter auto-generated vs uploaded resumes
    const gen = allResumes.find(isAutoGeneratedResume);
    const uploaded = allResumes.filter((r) => !isAutoGeneratedResume(r));

    setGeneratedResume(gen || null);
    setSavedUploadedResumes(uploaded);

    // Priority default:
    // 1. If user already has a generated resume -> use it!
    // 2. If user has an uploaded resume -> use uploaded
    // 3. Else -> new upload (or generate)
    if (gen) {
      setResumeChoice('generated');
    } else if (uploaded.length > 0) {
      setResumeChoice('saved_uploaded');
      setSelectedSavedUploadId(uploaded[0].id);
    } else {
      setResumeChoice('generated'); // will show 1-click generate button or switch to upload
    }

    if (uploaded.length > 0 && !selectedSavedUploadId) {
      setSelectedSavedUploadId(uploaded[0].id);
    }

    setLoadingResumes(false);
  }

  const ALLOWED_MIME_TYPES = [
    'application/pdf',
    'application/msword',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'image/jpeg',
    'image/jpg',
    'image/png',
  ];
  const ALLOWED_EXTENSIONS = ['.pdf', '.doc', '.docx', '.jpg', '.jpeg', '.png'];

  const handleFileChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    setErrorMessage('');
    const file = e.target.files?.[0];
    if (!file) return;

    const fileExt = '.' + file.name.split('.').pop()?.toLowerCase();
    const isAllowedExt = ALLOWED_EXTENSIONS.includes(fileExt);
    const isAllowedMime =
      ALLOWED_MIME_TYPES.includes(file.type) ||
      (file.type === '' && isAllowedExt);

    if (!isAllowedExt && !isAllowedMime) {
      setErrorMessage(
        'Invalid file format. Please upload a PDF, DOC, DOCX, JPG, or PNG file.'
      );
      e.target.value = '';
      return;
    }

    if (file.size > 15 * 1024 * 1024) {
      setErrorMessage('File size exceeds the 15MB limit. Please upload a smaller file.');
      e.target.value = '';
      return;
    }

    setUploadedFile(file);
    setResumeChoice('new_upload');
  };

  // Instant 1-click generation from profile inside ApplyModal
  const handleInstantGenerateInModal = async () => {
    if (!user || !profileData) return;
    setGeneratingOnTheFly(true);
    setErrorMessage('');

    try {
      const doc = await saveAutoGeneratedResume(user.id, profileData);
      setGeneratedResume(doc);
      setResumeChoice('generated');
    } catch (err: any) {
      console.error('Modal resume generate error:', err);
      setErrorMessage(err.message || 'Failed to auto-generate resume.');
    } finally {
      setGeneratingOnTheFly(false);
    }
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!user) {
      router.push('/auth/seeker/sign-in');
      return;
    }

    setErrorMessage('');
    setSubmitting(true);

    try {
      let finalResumeDocId: string | null = null;

      // 1. Option: Use Auto-Generated Resume
      if (resumeChoice === 'generated') {
        if (generatedResume) {
          finalResumeDocId = generatedResume.id;
        } else if (profileData) {
          // Auto-generate on the fly if not already generated
          setUploading(true);
          const doc = await saveAutoGeneratedResume(user.id, profileData);
          setGeneratedResume(doc);
          finalResumeDocId = doc.id;
          setUploading(false);
        } else {
          throw new Error('Please generate or select a resume before applying.');
        }
      }

      // 2. Option: Use Saved Uploaded Resume
      else if (resumeChoice === 'saved_uploaded') {
        if (!selectedSavedUploadId) {
          throw new Error('Please select an uploaded resume from your file list.');
        }
        finalResumeDocId = selectedSavedUploadId;
      }

      // 3. Option: Upload Another Resume File
      else if (resumeChoice === 'new_upload') {
        if (!uploadedFile) {
          throw new Error('Please select a resume file to upload.');
        }
        setUploading(true);
        const doc = await uploadResumeFile(user.id, uploadedFile);
        finalResumeDocId = doc.id;
        setUploading(false);
      }

      if (!finalResumeDocId) {
        throw new Error('No resume attached. Please choose or upload a resume.');
      }

      const response = await fetch('/api/applications', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          jobId: job.id,
          resumeDocumentId: finalResumeDocId,
          coverLetter: coverLetter.trim(),
        }),
      });
      const result = await response.json();
      if (!response.ok) {
        throw new Error(result.error || 'Failed to submit application.');
      }

      // 1. Notify Employer about the new applicant
      try {
        if (job.company_id) {
          const { data: employerData } = await supabase
            .from('employer_profiles')
            .select('user_id')
            .eq('company_id', job.company_id)
            .maybeSingle();

          if (employerData?.user_id) {
            await sendNotification({
              userId: employerData.user_id,
              type: 'application',
              title: 'New Applicant Received',
              message: `A candidate applied for ${job.title}. Candidate credentials and resume are ready.`,
              link: '/employer/applicants',
            });
          }
        }
      } catch (notifErr) {
        console.warn('Employer notification warning:', notifErr);
      }

      // 2. Notify Applicant confirming their application
      try {
        await sendNotification({
          userId: user.id,
          type: 'application',
          title: 'Application Submitted!',
          message: `You successfully applied for ${job.title} at ${job.company?.name || 'the hiring team'}.`,
          link: '/seeker/applications',
        });
      } catch (notifErr) {
        console.warn('Candidate notification warning:', notifErr);
      }

      setSuccess(true);
      if (onSuccess) onSuccess();
    } catch (err: any) {
      setErrorMessage(err.message || 'Failed to submit application. Please try again.');
    } finally {
      setSubmitting(false);
      setUploading(false);
    }
  };

  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title={success ? 'Application Submitted!' : `Apply for ${job.title}`}
      description={
        success
          ? `Your application has been received by ${job.company?.name || 'the hiring team'}.`
          : `Submit your profile and resume to ${job.company?.name || 'the hiring team'}`
      }
    >
      {success ? (
        <div className="text-center py-6 space-y-4">
          <div className="w-16 h-16 rounded-full bg-emerald-100 text-[#00b074] flex items-center justify-center mx-auto shadow-sm animate-in zoom-in">
            <CheckCircle2 className="w-9 h-9" />
          </div>
          <div className="space-y-1">
            <h3 className="text-lg font-bold text-dark">You&apos;re All Set!</h3>
            <p className="text-xs text-muted max-w-sm mx-auto">
              Your resume and credentials were sent directly to {job.company?.name || 'the recruiter'}. You can track the status in your applications hub.
            </p>
          </div>
          <div className="pt-3 flex flex-col sm:flex-row gap-2 justify-center">
            <Link href="/seeker/applications" onClick={onClose}>
              <Button variant="primary" size="sm" className="w-full sm:w-auto">
                View My Applications
              </Button>
            </Link>
            <Button variant="outline" size="sm" onClick={onClose} className="w-full sm:w-auto">
              Browse More Jobs
            </Button>
          </div>
        </div>
      ) : (
        <form onSubmit={handleSubmit} className="space-y-5">
          {errorMessage && (
            <div className="bg-rose-50 border border-rose-200 text-rose-800 text-xs p-3.5 rounded-2xl flex items-center gap-2">
              <AlertCircle className="w-4 h-4 text-rose-600 shrink-0" />
              <span>{errorMessage}</span>
            </div>
          )}

          {/* Job summary card snippet */}
          <div className="bg-slate-50 border border-border p-3.5 rounded-2xl flex items-center justify-between gap-3">
            <div className="flex items-center gap-3 min-w-0">
              <div className="w-10 h-10 rounded-xl bg-white border border-border flex items-center justify-center overflow-hidden shrink-0">
                {job.company?.logo_url ? (
                  <img
                    src={job.company.logo_url}
                    alt={job.company.name}
                    className="w-full h-full object-cover"
                  />
                ) : (
                  <Building2 className="w-5 h-5 text-slate-400" />
                )}
              </div>
              <div className="min-w-0">
                <h4 className="text-xs font-bold text-dark truncate">{job.title}</h4>
                <p className="text-[11px] text-muted truncate">
                  {job.company?.name} • {job.city || 'Remote'}
                </p>
              </div>
            </div>
            {matchScore > 0 && (
              <span className="bg-emerald-50 text-emerald-800 border border-emerald-200 text-[11px] font-extrabold px-2.5 py-1 rounded-full shrink-0 flex items-center gap-1">
                <Sparkles className="w-3 h-3 text-[#00b074]" /> {matchScore}% Match
              </span>
            )}
          </div>

          {/* ─── Resume Selection Section ────────────────────────────── */}
          <div className="space-y-3">
            <div className="flex items-center justify-between">
              <label className="block text-xs font-bold text-dark uppercase tracking-wider">
                Select Resume to Submit <span className="text-rose-500">*</span>
              </label>
              <span className="text-[11px] text-muted">
                Choose auto-generated, uploaded, or upload new
              </span>
            </div>

            {loadingResumes ? (
              <div className="p-6 text-center text-xs text-muted">
                <Loader2 className="w-5 h-5 animate-spin mx-auto text-[#00b074] mb-2" />
                Loading your resumes...
              </div>
            ) : (
              <div className="space-y-2.5">
                {/* ── Option 1: Auto-Generated Resume ── */}
                <div
                  onClick={() => setResumeChoice('generated')}
                  className={`p-3.5 rounded-2xl border transition-all cursor-pointer ${
                    resumeChoice === 'generated'
                      ? 'border-[#00b074] bg-[#f0fbf6] ring-1 ring-[#00b074]'
                      : 'border-border bg-white hover:border-slate-300'
                  }`}
                >
                  <div className="flex items-start justify-between gap-3">
                    <div className="flex items-start gap-3 min-w-0">
                      <div className="pt-0.5">
                        <input
                          type="radio"
                          name="resumeOption"
                          checked={resumeChoice === 'generated'}
                          onChange={() => setResumeChoice('generated')}
                          className="w-4 h-4 text-[#00b074] focus:ring-[#00b074]"
                        />
                      </div>
                      <div className="min-w-0">
                        <div className="flex flex-wrap items-center gap-2">
                          <span className="text-xs font-bold text-dark flex items-center gap-1">
                            <Sparkles className="w-3.5 h-3.5 text-[#00b074]" /> Auto-Generated Resume
                          </span>
                          <span className="text-[10px] font-bold px-2 py-0.2 rounded-full bg-emerald-100 text-emerald-800">
                            Verified Profile Data
                          </span>
                        </div>

                        {generatedResume ? (
                          <div className="text-[11px] text-muted mt-1 space-y-0.5">
                            <p className="font-medium text-slate-700 truncate">
                              📄 {generatedResume.file_name}
                            </p>
                            <p className="text-[10px] text-slate-400">
                              Generated on{' '}
                              {new Date(generatedResume.uploaded_at).toLocaleDateString()} • Ready to send
                            </p>
                          </div>
                        ) : (
                          <div className="mt-1.5 flex flex-wrap items-center gap-2">
                            <p className="text-[11px] text-muted">
                              No generated resume yet. Generate one instantly from your skills and experience:
                            </p>
                            <button
                              type="button"
                              onClick={(e) => {
                                e.stopPropagation();
                                handleInstantGenerateInModal();
                              }}
                              disabled={generatingOnTheFly}
                              className="px-2.5 py-1 rounded-lg bg-[#00b074] hover:bg-[#009b66] text-white text-[11px] font-bold flex items-center gap-1 shadow-2xs transition-all active:scale-95 cursor-pointer disabled:opacity-50"
                            >
                              {generatingOnTheFly ? (
                                <>
                                  <Loader2 className="w-3 h-3 animate-spin" /> Generating...
                                </>
                              ) : (
                                <>
                                  <Sparkles className="w-3 h-3" /> Generate Now (Instant)
                                </>
                              )}
                            </button>
                          </div>
                        )}
                      </div>
                    </div>
                  </div>
                </div>

                {/* ── Option 2: Use Saved Uploaded Resume ── */}
                <div
                  onClick={() => {
                    setResumeChoice('saved_uploaded');
                    if (savedUploadedResumes.length > 0 && !selectedSavedUploadId) {
                      setSelectedSavedUploadId(savedUploadedResumes[0].id);
                    }
                  }}
                  className={`p-3.5 rounded-2xl border transition-all cursor-pointer ${
                    resumeChoice === 'saved_uploaded'
                      ? 'border-[#00b074] bg-[#f0fbf6] ring-1 ring-[#00b074]'
                      : 'border-border bg-white hover:border-slate-300'
                  }`}
                >
                  <div className="flex items-start justify-between gap-3">
                    <div className="flex items-start gap-3 min-w-0 w-full">
                      <div className="pt-0.5">
                        <input
                          type="radio"
                          name="resumeOption"
                          checked={resumeChoice === 'saved_uploaded'}
                          onChange={() => setResumeChoice('saved_uploaded')}
                          disabled={savedUploadedResumes.length === 0}
                          className="w-4 h-4 text-[#00b074] focus:ring-[#00b074]"
                        />
                      </div>
                      <div className="min-w-0 w-full">
                        <div className="flex items-center gap-2">
                          <span className="text-xs font-bold text-dark flex items-center gap-1">
                            <FileText className="w-3.5 h-3.5 text-blue-600" /> Use Uploaded Resume
                          </span>
                          <span className="text-[10px] text-muted">
                            ({savedUploadedResumes.length} on file)
                          </span>
                        </div>

                        {savedUploadedResumes.length === 0 ? (
                          <p className="text-[11px] text-slate-400 mt-1">
                            No uploaded resumes on your profile yet.
                          </p>
                        ) : (
                          <div className="mt-2 w-full">
                            <select
                              value={selectedSavedUploadId}
                              onChange={(e) => setSelectedSavedUploadId(e.target.value)}
                              onClick={(e) => e.stopPropagation()}
                              className="w-full h-10 rounded-xl border border-border bg-white px-3 text-xs text-dark focus:border-[#00b074] focus:outline-none"
                            >
                              {savedUploadedResumes.map((res) => (
                                <option key={res.id} value={res.id}>
                                  {res.file_name} ({new Date(res.uploaded_at).toLocaleDateString()})
                                </option>
                              ))}
                            </select>
                          </div>
                        )}
                      </div>
                    </div>
                  </div>
                </div>

                {/* ── Option 3: Upload Another / New Resume File ── */}
                <div
                  onClick={() => setResumeChoice('new_upload')}
                  className={`p-3.5 rounded-2xl border transition-all cursor-pointer ${
                    resumeChoice === 'new_upload'
                      ? 'border-[#00b074] bg-[#f0fbf6] ring-1 ring-[#00b074]'
                      : 'border-border bg-white hover:border-slate-300'
                  }`}
                >
                  <div className="flex items-start gap-3">
                    <div className="pt-0.5">
                      <input
                        type="radio"
                        name="resumeOption"
                        checked={resumeChoice === 'new_upload'}
                        onChange={() => setResumeChoice('new_upload')}
                        className="w-4 h-4 text-[#00b074] focus:ring-[#00b074]"
                      />
                    </div>
                    <div className="min-w-0 flex-1">
                      <span className="text-xs font-bold text-dark flex items-center gap-1">
                        <UploadCloud className="w-3.5 h-3.5 text-slate-500" /> Upload Another Resume File
                      </span>

                      {/* Dropzone / Upload Trigger */}
                      {resumeChoice === 'new_upload' && (
                        <div className="mt-2.5">
                          <input
                            type="file"
                            id="applyModalUploadInput"
                            accept=".pdf,.doc,.docx,.jpg,.jpeg,.png,application/pdf,application/msword,application/vnd.openxmlformats-officedocument.wordprocessingml.document,image/jpeg,image/png"
                            onChange={handleFileChange}
                            className="hidden"
                          />
                          <label
                            htmlFor="applyModalUploadInput"
                            className="border-2 border-dashed border-border hover:border-[#00b074] rounded-xl p-3.5 text-center flex flex-col items-center justify-center gap-1.5 cursor-pointer bg-white transition-colors"
                          >
                            {uploadedFile ? (
                              <div className="flex items-center gap-2 text-xs font-bold text-emerald-800 bg-emerald-50 px-3 py-1.5 rounded-full border border-emerald-200">
                                <FileCheck className="w-4 h-4 text-[#00b074]" />
                                <span className="truncate max-w-xs">{uploadedFile.name}</span>
                                <span className="text-[10px] text-muted">
                                  ({(uploadedFile.size / 1024 / 1024).toFixed(2)} MB)
                                </span>
                              </div>
                            ) : (
                              <div>
                                <p className="text-xs font-semibold text-slate-700">
                                  Click to browse file
                                </p>
                                <p className="text-[10px] text-muted">
                                  PDF, DOC, DOCX, JPG, PNG (Max 15MB)
                                </p>
                              </div>
                            )}
                          </label>
                        </div>
                      )}
                    </div>
                  </div>
                </div>
              </div>
            )}
          </div>

          {/* Cover Note */}
          <div className="space-y-1.5">
            <label className="block text-xs font-bold text-dark uppercase tracking-wider">
              Cover Note to Employer (Optional)
            </label>
            <textarea
              rows={3}
              value={coverLetter}
              onChange={(e) => setCoverLetter(e.target.value)}
              placeholder="Highlight your key achievements, relevant projects, or reason for applying..."
              className="w-full rounded-xl border border-border p-3 text-xs text-dark focus:border-[#00b074] focus:outline-none"
            />
          </div>

          {/* Action buttons */}
          <div className="pt-2 border-t border-border flex items-center justify-end gap-2">
            <Button type="button" variant="outline" size="sm" onClick={onClose} disabled={submitting}>
              Cancel
            </Button>
            <Button
              type="submit"
              variant="primary"
              size="md"
              isLoading={submitting || uploading}
              className="font-bold shadow-sm"
            >
              <Send className="w-3.5 h-3.5" />
              {uploading ? 'Processing Resume...' : 'Submit Application'}
            </Button>
          </div>
        </form>
      )}
    </Modal>
  );
}
