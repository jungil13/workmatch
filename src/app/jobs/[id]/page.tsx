'use client';

import React, { useState, useEffect, use, useRef } from 'react';
import Link from 'next/link';
import { useRouter } from 'next/navigation';
import { Navbar } from '@/components/layout/Navbar';
import { Footer } from '@/components/layout/Footer';
import { supabase } from '@/lib/supabase/client';
import { formatRelativeTime } from '@/lib/utils';
import {
  ArrowLeft,
  Briefcase,
  MapPin,
  Clock,
  UploadCloud,
  CheckCircle2,
  Bookmark,
  BookmarkCheck,
  ShieldCheck,
  TrendingUp,
  Users,
  FileText,
  X,
  Sparkles,
  Loader2,
  Building2,
  Globe,
  Mail,
  Phone,
} from 'lucide-react';
import { fetchJobApplicantCounts, trackJobInteraction } from '@/lib/services/jobTrackingService';
import { fetchBackendJobMatches } from '@/lib/services/jobMatchService';
import { VerifiedCompanyBadge } from '@/components/ui/VerifiedCompanyBadge';
import { MatchBreakdownPopover } from '@/components/jobs/MatchBreakdownPopover';
import { MatchResult } from '@/types/matching';
import { Modal } from '@/components/ui/Modal';
import { CompanyPublicLinks } from '@/components/company/CompanyPublicLinks';
import {
  isAutoGeneratedResume,
  saveAutoGeneratedResume,
  uploadResumeFile,
} from '@/lib/services/resumeService';

const AVATAR_COLORS = [
  'bg-blue-600',
  'bg-emerald-600',
  'bg-orange-500',
  'bg-purple-600',
  'bg-rose-600',
  'bg-indigo-600',
  'bg-teal-600',
  'bg-amber-600',
];

export default function JobDetailsPage({ params }: { params: Promise<{ id: string }> }) {
  const resolvedParams = use(params);
  const router = useRouter();
  const fileInputRef = useRef<HTMLInputElement>(null);

  const [job, setJob] = useState<any | null>(null);
  const [loading, setLoading] = useState(true);
  const [userId, setUserId] = useState<string | null>(null);
  const [isSaved, setIsSaved] = useState(false);
  const [hasApplied, setHasApplied] = useState(false);
  const [applicantsCount, setApplicantsCount] = useState<number | null>(null);
  const [companyDetailsOpen, setCompanyDetailsOpen] = useState(false);
  const [matchScore, setMatchScore] = useState<number | null>(null);
  const [matchResult, setMatchResult] = useState<MatchResult | null>(null);
  const [matchMode, setMatchMode] = useState<'gemini-assisted' | 'exact' | null>(null);
  const [matchState, setMatchState] = useState<'signed-out' | 'profile-needed' | 'loading' | 'ready' | 'unavailable'>('signed-out');

  // Application form states
  const [resumeChoice, setResumeChoice] = useState<'generated' | 'saved_uploaded' | 'new_upload'>('generated');
  const [resumeFile, setResumeFile] = useState<File | null>(null);
  const [savedResumes, setSavedResumes] = useState<any[]>([]);
  const [generatedResume, setGeneratedResume] = useState<any | null>(null);
  const [savedUploadedResumes, setSavedUploadedResumes] = useState<any[]>([]);
  const [selectedSavedResumeId, setSelectedSavedResumeId] = useState<string>('');
  const [profileData, setProfileData] = useState<any>(null);
  const [generatingOnTheFly, setGeneratingOnTheFly] = useState(false);
  const [coverLetter, setCoverLetter] = useState('');
  const [submitting, setSubmitting] = useState(false);
  const [submitSuccess, setSubmitSuccess] = useState(false);
  const [errorMessage, setErrorMessage] = useState('');

  // Initial load
  useEffect(() => {
    async function loadData() {
      // 1. Fetch current user
      const { data: { user } } = await supabase.auth.getUser();
      let canLoadMatch = false;
      if (user) {
        setUserId(user.id);

        // Check if saved
        const { data: savedData } = await supabase
          .from('saved_jobs')
          .select('id')
          .eq('user_id', user.id)
          .eq('job_id', resolvedParams.id)
          .maybeSingle();
        if (savedData) setIsSaved(true);

        // Check if already applied
        const { data: appData } = await supabase
          .from('applications')
          .select('id')
          .eq('applicant_id', user.id)
          .eq('job_id', resolvedParams.id)
          .maybeSingle();
        if (appData) setHasApplied(true);

        // Fetch existing uploaded resumes & profile data
        const [docsRes, pRes, spRes, skRes, eduRes, expRes, certRes] = await Promise.all([
          supabase
            .from('documents')
            .select('*')
            .eq('user_id', user.id)
            .eq('document_type', 'resume')
            .order('uploaded_at', { ascending: false }),
          supabase.from('profiles').select('*').eq('id', user.id).maybeSingle(),
          supabase.from('job_seeker_profiles').select('*').eq('user_id', user.id).maybeSingle(),
          supabase.from('job_seeker_skills').select('*, skill:skills(*)').eq('user_id', user.id),
          supabase.from('educations').select('*').eq('user_id', user.id),
          supabase.from('work_experiences').select('*').eq('user_id', user.id),
          supabase.from('certifications').select('*').eq('user_id', user.id),
        ]);

        canLoadMatch = pRes.data?.role === 'job_seeker' && !!spRes.data;
        setMatchState(canLoadMatch ? 'loading' : 'profile-needed');
        setProfileData({
          profile: pRes.data || {},
          seekerProfile: spRes.data || {},
          skills: skRes.data ?? [],
          educations: eduRes.data ?? [],
          experiences: expRes.data ?? [],
          certifications: certRes.data ?? [],
        });

        const allResumes = docsRes.data ?? [];
        setSavedResumes(allResumes);

        const gen = allResumes.find(isAutoGeneratedResume);
        const uploaded = allResumes.filter((r) => !isAutoGeneratedResume(r));

        setGeneratedResume(gen || null);
        setSavedUploadedResumes(uploaded);

        if (gen) {
          setResumeChoice('generated');
        } else if (uploaded.length > 0) {
          setResumeChoice('saved_uploaded');
          setSelectedSavedResumeId(uploaded[0].id);
        } else {
          setResumeChoice('generated');
        }

        if (uploaded.length > 0) {
          setSelectedSavedResumeId(uploaded[0].id);
        }
      }

      // 2. Fetch Job Details
      const { data: jobData } = await supabase
        .from('jobs')
        .select('*, company:companies(*), required_skills:job_skills(*, skill:skills(*))')
        .eq('id', resolvedParams.id)
        .maybeSingle();

      if (jobData) {
        setJob(jobData);
        if (canLoadMatch) {
          void fetchBackendJobMatches([resolvedParams.id])
            .then((matches) => {
              const match = matches[resolvedParams.id];
              const score = match?.overallScore;
              if (typeof score === 'number') {
                setMatchResult(match);
                setMatchScore(score);
                setMatchMode(match.skillMatchMode || 'exact');
                setMatchState('ready');
              } else {
                setMatchState('unavailable');
              }
            })
            .catch((error) => {
              console.error('Could not load backend match score for job details:', error);
              setMatchState('unavailable');
            });
        }
        try {
          const counts = await fetchJobApplicantCounts([resolvedParams.id]);
          setApplicantsCount(counts[resolvedParams.id] ?? 0);
        } catch (error) {
          console.error('Could not load job applicant count:', error);
        }
        trackJobInteraction(resolvedParams.id, { source: 'page_view' }).catch(() => {});
      }
      setLoading(false);
    }

    loadData();
  }, [resolvedParams.id]);

  // Handle Save / Unsave
  const handleToggleSave = async () => {
    if (!userId) {
      router.push(`/auth/seeker/sign-in?redirect=/jobs/${resolvedParams.id}`);
      return;
    }
    if (isSaved) {
      await supabase.from('saved_jobs').delete().eq('user_id', userId).eq('job_id', resolvedParams.id);
      setIsSaved(false);
    } else {
      await supabase
        .from('saved_jobs')
        .upsert({ user_id: userId, job_id: resolvedParams.id }, { onConflict: 'user_id,job_id' });
      setIsSaved(true);
    }
  };

  // Handle Resume File Selection
  const handleFileChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    setErrorMessage('');
    const file = e.target.files?.[0];
    if (!file) return;

    const allowed = ['.pdf', '.doc', '.docx', '.jpg', '.jpeg', '.png'];
    const ext = '.' + file.name.split('.').pop()?.toLowerCase();
    if (!allowed.includes(ext)) {
      setErrorMessage('Please upload a PDF, DOCX, JPG, or PNG file.');
      return;
    }

    if (file.size > 15 * 1024 * 1024) {
      setErrorMessage('File size exceeds the 15MB limit.');
      return;
    }

    setResumeFile(file);
    setResumeChoice('new_upload');
  };

  // Instant 1-click Auto-Generate
  const handleInstantGenerate = async () => {
    if (!userId || !profileData) return;
    setGeneratingOnTheFly(true);
    setErrorMessage('');
    try {
      const doc = await saveAutoGeneratedResume(userId, profileData);
      setGeneratedResume(doc);
      setResumeChoice('generated');
    } catch (err: any) {
      console.error('Instant generate error:', err);
      setErrorMessage(err.message || 'Failed to auto-generate resume.');
    } finally {
      setGeneratingOnTheFly(false);
    }
  };

  // Submit Application
  const handleApplySubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!userId) {
      router.push(`/auth/seeker/sign-in?redirect=/jobs/${resolvedParams.id}`);
      return;
    }

    setSubmitting(true);
    setErrorMessage('');

    try {
      let finalResumeDocId: string | null = null;

      if (resumeChoice === 'generated') {
        if (generatedResume) {
          finalResumeDocId = generatedResume.id;
        } else if (profileData) {
          const doc = await saveAutoGeneratedResume(userId, profileData);
          setGeneratedResume(doc);
          finalResumeDocId = doc.id;
        } else {
          throw new Error('Please generate or select a resume before applying.');
        }
      } else if (resumeChoice === 'saved_uploaded') {
        if (!selectedSavedResumeId) {
          throw new Error('Please select an uploaded resume from your file list.');
        }
        finalResumeDocId = selectedSavedResumeId;
      } else if (resumeChoice === 'new_upload') {
        if (!resumeFile) {
          throw new Error('Please select a resume file to upload.');
        }
        const doc = await uploadResumeFile(userId, resumeFile);
        finalResumeDocId = doc.id;
      }

      if (!finalResumeDocId) {
        throw new Error('Please select or upload a resume before submitting.');
      }

      const response = await fetch('/api/applications', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          jobId: resolvedParams.id,
          resumeDocumentId: finalResumeDocId,
          coverLetter: coverLetter.trim(),
        }),
      });
      const result = await response.json();
      if (!response.ok) throw new Error(result.error || 'Failed to submit application.');

      setSubmitSuccess(true);
      setHasApplied(true);
      setApplicantsCount((count) => (count === null ? null : count + 1));
    } catch (err: any) {
      setErrorMessage(err.message || 'Error submitting application. Please try again.');
    } finally {
      setSubmitting(false);
    }
  };

  const getCompanyInitials = (name?: string) => {
    if (!name) return 'WM';
    return name
      .split(' ')
      .slice(0, 2)
      .map((w) => w[0])
      .join('')
      .toUpperCase();
  };

  const formatSalaryDisplay = (min?: number, max?: number, currency: string = 'PHP') => {
    const symbol = '₱';
    if (!min && !max) return `${symbol}60k - ${symbol}90k`;
    const formatK = (val: number) => {
      if (val >= 1000) return `${Math.round(val / 1000)}k`;
      return val.toLocaleString();
    };
    if (min && max && min !== max) {
      return `${symbol}${formatK(min)} - ${symbol}${formatK(max)}`;
    }
    return `${symbol}${formatK(min || max || 0)}`;
  };

  const parseBulletList = (text?: string, fallback: string[] = []): string[] => {
    if (!text) return fallback;
    const items = text
      .split(/\r?\n|•/)
      .map((s) => s.trim().replace(/^[-*•]\s*/, ''))
      .filter((s) => s.length > 2);
    return items.length > 0 ? items : fallback;
  };

  if (loading) {
    return (
      <div className="min-h-screen flex flex-col bg-[#f8fafc]">
        <Navbar />
        <main className="flex-1 flex items-center justify-center p-12">
          <div className="w-9 h-9 border-3 border-[#00b074] border-t-transparent rounded-full animate-spin" />
        </main>
        <Footer />
      </div>
    );
  }

  if (!job) {
    return (
      <div className="min-h-screen flex flex-col bg-[#f8fafc]">
        <Navbar />
        <main className="flex-1 flex flex-col items-center justify-center p-8 text-center">
          <h2 className="text-xl font-bold text-slate-800">Job Not Found</h2>
          <p className="text-xs text-slate-500 mt-1">This job opening may have expired or was removed.</p>
          <Link
            href="/jobs"
            className="mt-4 px-5 py-2.5 rounded-full bg-[#00b074] text-white text-xs font-semibold hover:bg-[#009b66] transition-all"
          >
            ← Back to Job Listings
          </Link>
        </main>
        <Footer />
      </div>
    );
  }

  const company = job.company || {};
  const initials = getCompanyInitials(company.name);
  const colorIndex = (job.id.charCodeAt(0) || 0) % AVATAR_COLORS.length;
  const avatarBg = AVATAR_COLORS[colorIndex];

  const defaultResponsibilities = [
    'Develop user-facing features using modern JavaScript frameworks',
    'Collaborate with backend developers to integrate APIs',
    'Optimize applications for maximum speed and scalability',
    'Write clean, maintainable, and well-documented code',
  ];

  const defaultQualifications = [
    '3+ years of experience in modern frontend development',
    'Strong proficiency in React, TypeScript, HTML, CSS',
    'Experience with state management tools and responsive web design',
    'Familiarity with RESTful APIs, Git workflows, and testing',
  ];

  const responsibilities = parseBulletList(job.responsibilities, defaultResponsibilities);
  const qualifications = parseBulletList(job.qualifications, defaultQualifications);

  return (
    <div className="min-h-screen flex flex-col bg-[#f8fafc] text-slate-800 selection:bg-emerald-200">
      <Navbar />

      <main className="flex-1 max-w-7xl mx-auto w-full px-4 sm:px-6 lg:px-8 py-6 space-y-6">
        {/* Back Link */}
        <div>
          <Link
            href="/jobs"
            className="inline-flex items-center gap-1.5 text-xs font-semibold text-slate-500 hover:text-slate-900 transition-colors"
          >
            <ArrowLeft className="w-3.5 h-3.5" /> Back to Job Listings
          </Link>
        </div>

        {/* 2-Column Layout Pixel-Matched to Reference Image */}
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-8 items-start">

          {/* ─── LEFT COLUMN: JOB DETAILS CARD ─────────────────────── */}
          <div className="lg:col-span-8 bg-white rounded-2xl border border-slate-200/90 p-6 sm:p-8 shadow-xs space-y-7">
            {/* Header: Avatar + Title & Meta + Match Score */}
            <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-4 pb-2 border-b border-slate-100">
              <div className="flex items-start gap-4 min-w-0">
                {/* Company Avatar */}
                <div
                  className={`w-14 h-14 rounded-2xl ${avatarBg} text-white font-bold text-lg flex items-center justify-center shrink-0 shadow-xs overflow-hidden`}
                >
                  {company.logo_url ? (
                    <img src={company.logo_url} alt={company.name} className="w-full h-full object-cover" />
                  ) : (
                    initials
                  )}
                </div>

                {/* Job Title + Company/Location + Tag Pills */}
                <div className="space-y-2 min-w-0">
                  <h1 className="text-xl sm:text-2xl font-black text-slate-900 tracking-tight leading-tight">
                    {job.title}
                  </h1>

                  {/* Company & Location */}
                  <div className="flex items-center gap-3 text-xs text-slate-500 font-normal">
                    <span className="flex items-center gap-1">
                      <Briefcase className="w-3.5 h-3.5 text-slate-400" />
                      {company.name || 'American Philippines'}
                    </span>
                    <VerifiedCompanyBadge company={company} />
                    <span className="flex items-center gap-1">
                      <MapPin className="w-3.5 h-3.5 text-slate-400" />
                      {job.city || company.city || 'Quezon City'}
                    </span>
                  </div>
                  <button
                    type="button"
                    onClick={() => setCompanyDetailsOpen(true)}
                    className="inline-flex items-center gap-1.5 text-xs font-semibold text-emerald-700 hover:text-emerald-800 hover:underline"
                  >
                    <Building2 className="w-3.5 h-3.5" />
                    See company details
                  </button>

                  {/* Tag Pills Row */}
                  <div className="flex flex-wrap items-center gap-2 pt-1">
                    <span className="text-xs font-semibold px-3 py-0.5 rounded-full bg-blue-50 text-blue-700 border border-blue-100/70">
                      {job.employment_type || 'Full-time'}
                    </span>
                    <span className="text-xs font-semibold px-3 py-0.5 rounded-full bg-emerald-50 text-emerald-700 border border-emerald-100/70">
                      {job.work_arrangement || 'Remote'}
                    </span>
                    <span className="text-xs font-semibold px-3 py-0.5 rounded-full bg-purple-50 text-purple-700 border border-purple-100/70">
                      {job.experience_level || 'Mid-Senior'}
                    </span>
                    <span className="text-xs font-medium px-3 py-0.5 rounded-full bg-slate-100 text-slate-600 flex items-center gap-1">
                      <Clock className="w-3 h-3 text-slate-400" />
                      Posted {job.created_at ? formatRelativeTime(job.created_at) : '2 days ago'}
                    </span>
                  </div>
                </div>
              </div>

              {/* Match Score Indicator (Right side of header) */}
              <div className="text-left sm:text-right shrink-0 sm:pl-4 self-start">
                {matchState === 'ready' && matchScore !== null ? (
                  <div className="flex items-center gap-1.5 justify-start sm:justify-end">
                    <span className="text-2xl sm:text-3xl font-black text-[#00b074] leading-none">
                      {matchScore}%
                    </span>
                    {matchResult && <MatchBreakdownPopover match={matchResult} />}
                  </div>
                ) : (
                  <div className="text-xs font-semibold text-slate-500">
                    {matchState === 'loading'
                      ? 'Calculating…'
                      : matchState === 'signed-out'
                        ? 'Sign in for a personal match'
                        : matchState === 'profile-needed'
                          ? 'Complete your seeker profile'
                          : 'Match unavailable'}
                  </div>
                )}
                <p className="text-[11px] text-slate-400 font-medium tracking-tight mt-1">
                  {matchState === 'ready'
                    ? matchMode === 'gemini-assisted'
                      ? 'AI-assisted estimate'
                      : 'Profile compatibility estimate'
                    : 'Personal match'}
                </p>
              </div>
            </div>

            {/* Job Description */}
            <div className="space-y-3">
              <h2 className="text-base font-bold text-slate-900">Job Description</h2>
              <p className="text-xs sm:text-sm text-slate-600 leading-relaxed">
                {job.description ||
                  `We are looking for a ${job.title} to build scalable and high-performance web applications. You will work closely with designers, backend developers, and stakeholders to deliver great user experiences.`}
              </p>
            </div>

            {/* Required Skills Section */}
            {job.required_skills && job.required_skills.length > 0 && (
              <div className="space-y-3">
                <div className="flex items-center justify-between">
                  <h2 className="text-base font-bold text-slate-900 flex items-center gap-2">
                    <Sparkles className="w-4 h-4 text-[#00b074]" /> Required Skills
                  </h2>
                  <span className="text-xs text-slate-400 font-medium">
                    {job.required_skills.length} listed
                  </span>
                </div>
                <div className="flex flex-wrap gap-2">
                  {job.required_skills.map((item: any, idx: number) => {
                    const sName = item.name || item.skill?.name || 'Skill';
                    const sCategory = item.category || item.skill?.category;
                    const minProf = item.minimum_proficiency;
                    const isMatched = matchResult?.matchedSkillNames?.some(
                      (m) => m.toLowerCase() === sName.toLowerCase()
                    );
                    return (
                      <span
                        key={item.id || idx}
                        className={`inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl text-xs font-semibold border transition-all ${
                          isMatched
                            ? 'bg-emerald-50 text-emerald-800 border-emerald-200'
                            : 'bg-slate-50 text-slate-700 border-slate-200'
                        }`}
                      >
                        {isMatched ? (
                          <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600 shrink-0" />
                        ) : (
                          <span className="w-1.5 h-1.5 rounded-full bg-slate-400 shrink-0" />
                        )}
                        <span>{sName}</span>
                        {minProf && (
                          <span className="text-[10px] text-slate-400 font-normal">
                            (Lvl {minProf}/5)
                          </span>
                        )}
                        {sCategory && (
                          <span className="text-[9px] px-1.5 py-0.5 rounded-md bg-white border border-slate-200 text-slate-500 font-normal">
                            {sCategory}
                          </span>
                        )}
                      </span>
                    );
                  })}
                </div>
              </div>
            )}

            {/* Responsibilities */}
            <div className="space-y-3">
              <h2 className="text-base font-bold text-slate-900">Responsibilities:</h2>
              <ul className="space-y-2 text-xs sm:text-sm text-slate-600">
                {responsibilities.map((item, idx) => (
                  <li key={idx} className="flex items-start gap-2.5">
                    <span className="w-1.5 h-1.5 rounded-full bg-[#00b074] mt-2 shrink-0" />
                    <span className="leading-relaxed">{item}</span>
                  </li>
                ))}
              </ul>
            </div>

            {/* Qualifications */}
            <div className="space-y-3">
              <h2 className="text-base font-bold text-slate-900">Qualifications:</h2>
              <ul className="space-y-2 text-xs sm:text-sm text-slate-600">
                {qualifications.map((item, idx) => (
                  <li key={idx} className="flex items-start gap-2.5">
                    <span className="w-1.5 h-1.5 rounded-full bg-[#00b074] mt-2 shrink-0" />
                    <span className="leading-relaxed">{item}</span>
                  </li>
                ))}
              </ul>
            </div>
          </div>

          {/* ─── RIGHT COLUMN: APPLY FOR THIS JOB CARD ──────────────── */}
          <div className="lg:col-span-4 sticky top-6">
            <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-5">
              <h3 className="text-base font-bold text-slate-900">Apply for this job</h3>

              {/* Salary Range */}
              <div className="space-y-0.5 pb-2">
                <span className="text-xs text-slate-500 font-medium flex items-center gap-1">
                  Salary Range
                </span>
                <p className="text-xl font-black text-slate-900 tracking-tight">
                  {formatSalaryDisplay(job.salary_min, job.salary_max, job.salary_currency || 'PHP')}
                </p>
                <p className="text-xs text-slate-400 font-normal">
                  Expected salary per year
                </p>
              </div>

              {/* Application Form */}
              {submitSuccess ? (
                <div className="p-5 rounded-2xl bg-emerald-50 border border-emerald-200 text-center space-y-3">
                  <div className="w-12 h-12 rounded-full bg-emerald-500 text-white flex items-center justify-center mx-auto shadow-sm">
                    <CheckCircle2 className="w-6 h-6" />
                  </div>
                  <h4 className="text-sm font-bold text-slate-900">Application Submitted!</h4>
                  <p className="text-xs text-slate-600">
                    Your resume and details were sent to <strong>{company.name || 'the employer'}</strong>.
                  </p>
                  <Link
                    href="/jobs"
                    className="inline-block mt-2 text-xs font-semibold text-[#00b074] hover:underline"
                  >
                    Browse more jobs →
                  </Link>
                </div>
              ) : (
                <form onSubmit={handleApplySubmit} className="space-y-4">
                  {/* Resume Selection */}
                  <div className="space-y-2">
                    <div className="flex items-center justify-between">
                      <label className="text-xs font-bold text-slate-800">
                        Resume to Submit <span className="text-rose-500">*</span>
                      </label>
                      <span className="text-[10px] text-slate-400">
                        Auto-generated or uploaded
                      </span>
                    </div>

                    {/* Hidden input */}
                    <input
                      ref={fileInputRef}
                      type="file"
                      accept=".pdf,.doc,.docx,.jpg,.jpeg,.png"
                      onChange={handleFileChange}
                      className="hidden"
                    />

                    {/* Option 1: Auto-Generated Resume */}
                    <div
                      onClick={() => setResumeChoice('generated')}
                      className={`p-2.5 rounded-xl border text-xs cursor-pointer transition-all ${
                        resumeChoice === 'generated'
                          ? 'border-[#00b074] bg-emerald-50/50 ring-1 ring-[#00b074]'
                          : 'border-slate-200 bg-white hover:border-slate-300'
                      }`}
                    >
                      <div className="flex items-start gap-2">
                        <input
                          type="radio"
                          name="jobResumeOption"
                          checked={resumeChoice === 'generated'}
                          onChange={() => setResumeChoice('generated')}
                          className="mt-0.5 w-3.5 h-3.5 text-[#00b074] focus:ring-[#00b074]"
                        />
                        <div className="min-w-0 flex-1">
                          <div className="flex items-center gap-1.5">
                            <span className="font-bold text-slate-800 flex items-center gap-1">
                              <Sparkles className="w-3 h-3 text-[#00b074]" /> Auto-Generated Resume
                            </span>
                            <span className="text-[9px] font-extrabold px-1.5 py-0.2 rounded-full bg-emerald-100 text-emerald-800">
                              Profile
                            </span>
                          </div>

                          {generatedResume ? (
                            <p className="text-[11px] text-slate-600 truncate mt-0.5">
                              📄 {generatedResume.file_name}
                            </p>
                          ) : (
                            <div className="mt-1 flex items-center gap-1.5">
                              <span className="text-[10px] text-slate-400">None generated yet.</span>
                              <button
                                type="button"
                                onClick={(e) => {
                                  e.stopPropagation();
                                  handleInstantGenerate();
                                }}
                                disabled={generatingOnTheFly}
                                className="text-[10px] font-bold text-[#00b074] hover:underline flex items-center gap-1"
                              >
                                {generatingOnTheFly ? (
                                  <>
                                    <Loader2 className="w-2.5 h-2.5 animate-spin" /> Generating...
                                  </>
                                ) : (
                                  '+ Generate Now'
                                )}
                              </button>
                            </div>
                          )}
                        </div>
                      </div>
                    </div>

                    {/* Option 2: Use Saved Uploaded Resume */}
                    {savedUploadedResumes.length > 0 && (
                      <div
                        onClick={() => {
                          setResumeChoice('saved_uploaded');
                          if (savedUploadedResumes.length > 0 && !selectedSavedResumeId) {
                            setSelectedSavedResumeId(savedUploadedResumes[0].id);
                          }
                        }}
                        className={`p-2.5 rounded-xl border text-xs cursor-pointer transition-all ${
                          resumeChoice === 'saved_uploaded'
                            ? 'border-[#00b074] bg-emerald-50/50 ring-1 ring-[#00b074]'
                            : 'border-slate-200 bg-white hover:border-slate-300'
                        }`}
                      >
                        <div className="flex items-start gap-2">
                          <input
                            type="radio"
                            name="jobResumeOption"
                            checked={resumeChoice === 'saved_uploaded'}
                            onChange={() => setResumeChoice('saved_uploaded')}
                            className="mt-0.5 w-3.5 h-3.5 text-[#00b074] focus:ring-[#00b074]"
                          />
                          <div className="min-w-0 flex-1">
                            <span className="font-bold text-slate-800 flex items-center gap-1">
                              <FileText className="w-3 h-3 text-blue-600" /> Saved Uploaded Resume
                            </span>
                            <div className="mt-1.5">
                              <select
                                value={selectedSavedResumeId}
                                onChange={(e) => setSelectedSavedResumeId(e.target.value)}
                                onClick={(e) => e.stopPropagation()}
                                className="w-full h-8 rounded-lg border border-slate-200 bg-white px-2 text-[11px] text-slate-800 focus:border-[#00b074] focus:outline-none"
                              >
                                {savedUploadedResumes.map((res) => (
                                  <option key={res.id} value={res.id}>
                                    {res.file_name} ({new Date(res.uploaded_at).toLocaleDateString()})
                                  </option>
                                ))}
                              </select>
                            </div>
                          </div>
                        </div>
                      </div>
                    )}

                    {/* Option 3: Upload Another Resume File */}
                    <div
                      onClick={() => setResumeChoice('new_upload')}
                      className={`p-2.5 rounded-xl border text-xs cursor-pointer transition-all ${
                        resumeChoice === 'new_upload'
                          ? 'border-[#00b074] bg-emerald-50/50 ring-1 ring-[#00b074]'
                          : 'border-slate-200 bg-white hover:border-slate-300'
                      }`}
                    >
                      <div className="flex items-start gap-2">
                        <input
                          type="radio"
                          name="jobResumeOption"
                          checked={resumeChoice === 'new_upload'}
                          onChange={() => setResumeChoice('new_upload')}
                          className="mt-0.5 w-3.5 h-3.5 text-[#00b074] focus:ring-[#00b074]"
                        />
                        <div className="min-w-0 flex-1">
                          <span className="font-bold text-slate-800 flex items-center gap-1">
                            <UploadCloud className="w-3 h-3 text-slate-500" /> Upload Another Resume File
                          </span>

                          {resumeChoice === 'new_upload' && (
                            <div className="mt-2">
                              {resumeFile ? (
                                <div className="border border-emerald-200 bg-emerald-50/70 rounded-lg p-2 flex items-center justify-between gap-1.5">
                                  <span className="text-[11px] font-semibold text-emerald-900 truncate">
                                    {resumeFile.name}
                                  </span>
                                  <button
                                    type="button"
                                    onClick={(e) => {
                                      e.stopPropagation();
                                      setResumeFile(null);
                                    }}
                                    className="text-slate-400 hover:text-rose-600"
                                  >
                                    <X className="w-3 h-3" />
                                  </button>
                                </div>
                              ) : (
                                <div
                                  onClick={(e) => {
                                    e.stopPropagation();
                                    fileInputRef.current?.click();
                                  }}
                                  className="border border-dashed border-slate-300 hover:border-[#00b074] rounded-lg p-2.5 text-center cursor-pointer transition-colors"
                                >
                                  <p className="text-[11px] font-medium text-slate-700">
                                    Click to select file
                                  </p>
                                  <p className="text-[10px] text-slate-400">PDF, DOCX, JPG, PNG</p>
                                </div>
                              )}
                            </div>
                          )}
                        </div>
                      </div>
                    </div>
                  </div>

                  {/* Cover Letter */}
                  <div className="space-y-1.5">
                    <label className="text-xs font-bold text-slate-800">Cover Letter</label>
                    <textarea
                      placeholder="Write a brief cover letter..."
                      value={coverLetter}
                      onChange={(e) => setCoverLetter(e.target.value)}
                      className="w-full h-28 rounded-xl border border-slate-200 p-3 text-xs text-slate-800 placeholder:text-slate-400 focus:border-[#00b074] focus:ring-1 focus:ring-[#00b074] focus:outline-none resize-none transition-all"
                    />
                    <p className="text-[11px] text-slate-400 font-normal">
                      Optional but recommended
                    </p>
                  </div>

                  {/* Error Notification */}
                  {errorMessage && (
                    <div className="p-2.5 rounded-lg bg-rose-50 border border-rose-200 text-rose-700 text-xs font-medium">
                      {errorMessage}
                    </div>
                  )}

                  {/* Apply Now Primary Button */}
                  <button
                    type="submit"
                    disabled={submitting || hasApplied}
                    className="w-full py-3.5 rounded-xl bg-[#00b074] hover:bg-[#009b66] text-white text-xs font-bold transition-all shadow-sm active:scale-[0.99] disabled:opacity-60 cursor-pointer"
                  >
                    {submitting
                      ? 'Submitting Application...'
                      : hasApplied
                      ? 'Already Applied'
                      : 'Apply Now'}
                  </button>

                  {/* Save Job Button */}
                  <button
                    type="button"
                    onClick={handleToggleSave}
                    className="w-full py-3 rounded-xl border border-slate-200 bg-white hover:bg-slate-50 text-slate-700 text-xs font-semibold flex items-center justify-center gap-2 transition-colors cursor-pointer"
                  >
                    {isSaved ? (
                      <>
                        <BookmarkCheck className="w-4 h-4 text-[#00b074]" /> Saved
                      </>
                    ) : (
                      <>
                        <Bookmark className="w-4 h-4 text-slate-400" /> Save Job
                      </>
                    )}
                  </button>

                  {/* Trust Badge */}
                  <div className="flex items-center justify-center gap-1.5 text-[11px] text-slate-500 pt-1">
                    <ShieldCheck className="w-4 h-4 text-[#00b074]" />
                    <span>Your application is secure and confidential</span>
                  </div>
                </form>
              )}

              {/* Bottom Meta Row */}
              <div className="pt-3 border-t border-slate-100 flex items-center justify-between text-xs text-slate-500">
                <span className="flex items-center gap-1.5 font-medium">
                  <Users className="w-3.5 h-3.5 text-slate-400" />
                  {applicantsCount === null ? 'Applicant count unavailable' : `${applicantsCount} applicants`}
                </span>
                <span className="flex items-center gap-1 font-semibold text-[#00b074]">
                  <TrendingUp className="w-3.5 h-3.5" /> High demand
                </span>
              </div>
            </div>
          </div>
        </div>
      </main>

      <Modal
        isOpen={companyDetailsOpen}
        onClose={() => setCompanyDetailsOpen(false)}
        title="Company Details"
        maxWidth="2xl"
      >
        <div className="space-y-6">
          <div className="flex items-start gap-4 pr-8">
            <div className="w-16 h-16 rounded-2xl border border-slate-200 bg-slate-50 flex items-center justify-center overflow-hidden shrink-0">
              {company.logo_url ? (
                <img src={company.logo_url} alt={company.name || 'Company logo'} className="w-full h-full object-cover" />
              ) : (
                <Building2 className="w-8 h-8 text-slate-400" />
              )}
            </div>
            <div className="min-w-0 space-y-1">
              <h2 className="text-lg font-black text-slate-900">{company.name || 'Company'}</h2>
              <VerifiedCompanyBadge company={company} />
              {company.industry && <p className="text-sm font-medium text-emerald-700">{company.industry}</p>}
            </div>
          </div>

          <section className="space-y-2">
            <h3 className="text-xs font-bold uppercase tracking-wide text-slate-500">About</h3>
            <p className="text-sm leading-relaxed text-slate-700">
              {company.description || 'No company description provided.'}
            </p>
          </section>

          <section className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            <div className="space-y-1">
              <h3 className="text-xs font-bold uppercase tracking-wide text-slate-500">Address</h3>
              <p className="text-sm text-slate-700">
                {[company.address, company.city, company.province, company.postal_code].filter(Boolean).join(', ') || 'Not provided'}
              </p>
            </div>
            {company.email && (
              <div className="space-y-1">
                <h3 className="text-xs font-bold uppercase tracking-wide text-slate-500">Email</h3>
                <a href={`mailto:${company.email}`} className="inline-flex items-center gap-1.5 text-sm font-medium text-emerald-700 hover:underline break-all">
                  <Mail className="w-3.5 h-3.5 shrink-0" /> {company.email}
                </a>
              </div>
            )}
            {company.phone && (
              <div className="space-y-1">
                <h3 className="text-xs font-bold uppercase tracking-wide text-slate-500">Phone</h3>
                <a href={`tel:${company.phone}`} className="inline-flex items-center gap-1.5 text-sm font-medium text-emerald-700 hover:underline">
                  <Phone className="w-3.5 h-3.5 shrink-0" /> {company.phone}
                </a>
              </div>
            )}
            {company.website && (
              <div className="space-y-1">
                <h3 className="text-xs font-bold uppercase tracking-wide text-slate-500">Website</h3>
                <a href={company.website} target="_blank" rel="noopener noreferrer" className="inline-flex items-center gap-1.5 text-sm font-medium text-emerald-700 hover:underline break-all">
                  <Globe className="w-3.5 h-3.5 shrink-0" /> {company.website}
                </a>
              </div>
            )}
          </section>

          <CompanyPublicLinks company={company} />

          <Link
            href={`/companies/${company.id}`}
            onClick={() => setCompanyDetailsOpen(false)}
            className="inline-flex text-xs font-bold text-emerald-700 hover:underline"
          >
            View company page
          </Link>
        </div>
      </Modal>

      <Footer />
    </div>
  );
}
