'use client';

import React, { useState, useEffect, use } from 'react';
import Link from 'next/link';
import { DashboardLayout } from '@/components/layout/DashboardLayout';
import { Button } from '@/components/ui/Button';
import { supabase } from '@/lib/supabase/client';
import { downloadDocument, isAutoGeneratedResume } from '@/lib/services/resumeService';
import {
  ArrowLeft,
  Sparkles,
  MapPin,
  Briefcase,
  GraduationCap,
  Download,
  Phone,
  Mail,
  Check,
  FileText,
  Award,
} from 'lucide-react';

import { APPLICATION_STATUS_COLORS, APPLICATION_STATUS_LABELS, EMPLOYER_STATUS_OPTIONS } from '@/lib/applicationStatus';

const STATUS_OPTIONS = EMPLOYER_STATUS_OPTIONS.map((s) => ({
  value: s.value,
  label: s.label,
  color: APPLICATION_STATUS_COLORS[s.value] || 'text-slate-700 bg-slate-50 border-slate-200',
}));

export default function EmployerApplicantDetailPage({ params }: { params: Promise<{ id: string }> }) {
  const resolvedParams = use(params);
  const [application, setApplication] = useState<any | null>(null);
  const [loading, setLoading] = useState(true);
  const [isUpdating, setIsUpdating] = useState(false);
  const [documentUrls, setDocumentUrls] = useState<Record<string, string>>({});
  const [documentErrors, setDocumentErrors] = useState<Record<string, string>>({});
  const [loadError, setLoadError] = useState('');

  useEffect(() => {
    let channel: any = null;
    fetchApplication().then(() => {
      channel = supabase
        .channel(`public:applications:${resolvedParams.id}-${Date.now()}`)
        .on(
          'postgres_changes',
          { event: '*', schema: 'public', table: 'applications', filter: `id=eq.${resolvedParams.id}` },
          () => {
            fetchApplication();
          }
        )
        .subscribe();
    });

    return () => {
      if (channel) supabase.removeChannel(channel);
    };
  }, [resolvedParams.id]);

  useEffect(() => {
    if (!application?.applicant_id) return;
    const channel = supabase
      .channel(`candidate-employment-${application.applicant_id}-${Date.now()}`)
      .on(
        'postgres_changes',
        {
          event: 'UPDATE',
          schema: 'public',
          table: 'job_seeker_profiles',
          filter: `user_id=eq.${application.applicant_id}`,
        },
        () => {
          fetchApplication();
        }
      )
      .subscribe();
    return () => {
      supabase.removeChannel(channel);
    };
  }, [application?.applicant_id]);

  async function fetchApplication() {
    const { data, error } = await supabase
      .from('applications')
      .select(`
        *,
        job:jobs(*, company:companies(*)),
        resume:documents(*),
        applicant:profiles(
          id, first_name, last_name, email, phone, avatar_url,
          job_seeker_profile:job_seeker_profiles(*),
          skills:job_seeker_skills(*, skill:skills(*)),
          educations(*),
          work_experiences(*)
        )
      `)
      .eq('id', resolvedParams.id)
      .maybeSingle();

    if (error) {
      console.error('Error loading applicant application:', error);
      setLoadError('Could not load applicant details. Please refresh the page and try again.');
      setApplication(null);
      setLoading(false);
      return;
    }

    if (!data) {
      setApplication(null);
      setLoading(false);
      return;
    }

    const [documentsResult, certificationsResult] = await Promise.all([
      supabase
        .from('documents')
        .select('*')
        .eq('user_id', data.applicant_id)
        .order('uploaded_at', { ascending: false }),
      supabase
        .from('certifications')
        .select('*')
        .eq('user_id', data.applicant_id)
        .order('issue_date', { ascending: false }),
    ]);

    if (documentsResult.error) {
      console.error('Error loading applicant documents:', documentsResult.error);
    }
    if (certificationsResult.error) {
      console.error('Error loading applicant certifications:', certificationsResult.error);
    }

    setApplication({
      ...data,
      applicant: data.applicant
        ? {
            ...data.applicant,
            documents: documentsResult.data ?? [],
            certifications: certificationsResult.data ?? [],
          }
        : data.applicant,
    });
    setLoadError('');
    setLoading(false);
  }

  useEffect(() => {
    const applicantDocuments = application?.applicant?.documents ?? [];
    const documents = [
      ...applicantDocuments,
      ...(application?.resume && !applicantDocuments.some((doc: any) => doc.id === application.resume.id)
        ? [application.resume]
        : []),
    ];
    let cancelled = false;

    setDocumentUrls({});
    setDocumentErrors({});

    Promise.all(
      documents.map(async (doc: any) => {
        try {
          const response = await fetch(`/api/documents/signed-url?documentId=${encodeURIComponent(doc.id)}`);
          const data = await response.json();
          if (!response.ok || !data.url) {
            throw new Error(data.error || 'Could not create a secure document preview.');
          }
          return { id: doc.id, url: data.url as string };
        } catch (error) {
          return {
            id: doc.id,
            error: error instanceof Error ? error.message : 'Could not load this document.',
          };
        }
      })
    ).then((results) => {
      if (cancelled) return;
      setDocumentUrls(Object.fromEntries(results.filter((result) => 'url' in result).map((result) => [result.id, result.url])));
      setDocumentErrors(Object.fromEntries(results.filter((result) => 'error' in result).map((result) => [result.id, result.error])));
    });

    return () => {
      cancelled = true;
    };
  }, [application?.applicant?.documents, application?.resume]);

  const handleDownloadGeneratedResume = async (doc: any) => {
    if (!doc) return;
    try {
      // Build the applicant profile data so auto-generated resumes can be re-rendered as PDF
      const profileData = application?.applicant ? {
        profile:      application.applicant,
        seekerProfile: application.applicant.job_seeker_profile ?? {},
        skills:       application.applicant.skills ?? [],
        educations:   application.applicant.educations ?? [],
        experiences:  application.applicant.work_experiences ?? [],
      } : undefined;

      await downloadDocument(doc, doc.file_name, profileData, doc.user_id || application?.applicant?.id);
    } catch (err: any) {
      console.error('Error downloading generated resume:', err);
      alert(err.message || 'Failed to download resume. Please try again.');
    }
  };

  const handleStatusChange = async (newStatus: string) => {
    if (!application) return;
    setIsUpdating(true);
    const res = await fetch('/api/applications/update-status', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ applicationId: application.id, status: newStatus }),
    });
    const data = await res.json();
    if (res.ok) {
      setApplication((prev: any) => ({ ...prev, status: newStatus }));
    } else {
      alert(data.error || 'Could not update status.');
    }
    setIsUpdating(false);
  };

  if (loading) {
    return (
      <DashboardLayout portal="employer" title="Applicant Details">
        <div className="flex items-center justify-center h-48">
          <div className="w-8 h-8 border-3 border-[#00b074] border-t-transparent rounded-full animate-spin" />
        </div>
      </DashboardLayout>
    );
  }

  if (!application) {
    return (
      <DashboardLayout portal="employer" title="Applicant Details">
        <div className="bg-white rounded-3xl border border-border p-12 text-center space-y-3">
          <h3 className="text-base font-bold text-dark">{loadError ? 'Unable to Load Applicant' : 'Applicant Not Found'}</h3>
          <p className="text-xs text-muted">
            {loadError || 'This application may have been removed or does not exist.'}
          </p>
          <Link href="/employer/applicants">
            <Button variant="outline" size="sm" className="mt-4">
              ← Back to Applicants
            </Button>
          </Link>
        </div>
      </DashboardLayout>
    );
  }

  const phone = application.applicant?.phone;
  const email = application.applicant?.email;
  const currentStatusObj = STATUS_OPTIONS.find((s) => s.value === application.status) || {
    value: application.status,
    label: APPLICATION_STATUS_LABELS[application.status] || application.status,
    color: APPLICATION_STATUS_COLORS[application.status] || 'text-slate-700 bg-slate-50 border-slate-200',
  };
  const seekerProfile = application.applicant?.job_seeker_profile;
  const applicantDocuments = [
    ...(application.applicant?.documents ?? []),
    ...(application.resume && !(application.applicant?.documents ?? []).some((doc: any) => doc.id === application.resume.id)
      ? [application.resume]
      : []),
  ];
  const hiredElsewhere =
    seekerProfile?.employment_status === 'hired' && seekerProfile?.hired_application_id !== application.id;
  const statusLocked = application.status === 'hired' || hiredElsewhere;

  return (
    <DashboardLayout
      portal="employer"
      title={`${application.applicant?.first_name || 'Candidate'} ${application.applicant?.last_name || ''}`}
      subtitle={`Application for ${application.job?.title || 'Open Position'}`}
      actions={
        <Link href="/employer/applicants">
          <Button variant="outline" size="sm" className="flex items-center gap-1.5 text-xs font-semibold">
            <ArrowLeft className="w-4 h-4" /> Back to Applicants
          </Button>
        </Link>
      }
    >
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 max-w-7xl items-start">
        {/* Left Column: Candidate Profile & Resume */}
        <div className="lg:col-span-8 space-y-6">
          {/* Main Candidate Card */}
          <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-6">
            <div className="flex flex-col sm:flex-row sm:items-start justify-between gap-4">
              <div className="flex items-center gap-4">
                {application.applicant?.avatar_url ? (
                  <img
                    src={application.applicant.avatar_url}
                    alt={application.applicant.first_name}
                    className="w-16 h-16 rounded-2xl object-cover border border-emerald-200 shadow-xs shrink-0"
                  />
                ) : (
                  <div className="w-16 h-16 rounded-2xl bg-[#00b074] text-white font-black text-xl flex items-center justify-center shrink-0 shadow-xs">
                    {application.applicant?.first_name?.[0] || 'U'}
                    {application.applicant?.last_name?.[0] || ''}
                  </div>
                )}
                <div>
                  <h3 className="text-xl font-black text-slate-900">
                    {application.applicant?.first_name} {application.applicant?.last_name}
                  </h3>
                  <p className="text-xs font-semibold text-emerald-700 mt-0.5">
                    {application.applicant?.job_seeker_profile?.professional_title || 'Job Seeker'}
                  </p>
                  <p className="text-xs text-slate-500 flex items-center gap-1.5 mt-1">
                    <MapPin className="w-3.5 h-3.5 text-slate-400" />
                    {application.applicant?.job_seeker_profile?.city || 'Location not specified'}
                  </p>
                </div>
              </div>

              <div className="bg-slate-50 border border-slate-200 p-3 rounded-xl text-center shrink-0">
                <span className="text-[10px] font-bold text-slate-400 uppercase tracking-wider block">
                  Application For
                </span>
                <strong className="text-xs font-bold text-slate-900">{application.job?.title}</strong>
              </div>
            </div>

            {application.applicant?.job_seeker_profile?.bio && (
              <div className="pt-4 border-t border-slate-100 space-y-1.5">
                <span className="text-[11px] font-bold text-slate-400 uppercase tracking-wider block">
                  About Candidate
                </span>
                <p className="text-xs text-slate-600 leading-relaxed whitespace-pre-line">
                  {application.applicant.job_seeker_profile.bio}
                </p>
              </div>
            )}

            {/* Cover Letter if provided */}
            {application.cover_letter && (
              <div className="pt-4 border-t border-slate-100 space-y-1.5">
                <span className="text-[11px] font-bold text-slate-400 uppercase tracking-wider block">
                  Cover Letter
                </span>
                <p className="text-xs text-slate-700 leading-relaxed bg-slate-50 p-4 rounded-xl border border-slate-200/70 whitespace-pre-line">
                  {application.cover_letter}
                </p>
              </div>
            )}

          </div>

          {/* Profile Details */}
          <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-4">
              <h4 className="text-xs font-bold text-slate-900 flex items-center gap-2">
                <Briefcase className="w-4 h-4 text-[#00b074]" /> Career Details &amp; Preferences
              </h4>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                {[
                  ['Experience', `${seekerProfile?.years_experience ?? 0} years`],
                  ['Availability', seekerProfile?.availability || 'Not specified'],
                  ['Preferred job type', seekerProfile?.preferred_job_type || 'Not specified'],
                  ['Work arrangement', seekerProfile?.preferred_work_arrangement || 'Not specified'],
                  [
                    'Expected monthly salary',
                    seekerProfile?.preferred_salary_min || seekerProfile?.preferred_salary_max
                      ? `${seekerProfile.preferred_salary_min ? `₱${Number(seekerProfile.preferred_salary_min).toLocaleString()}` : 'Not specified'} – ${seekerProfile.preferred_salary_max ? `₱${Number(seekerProfile.preferred_salary_max).toLocaleString()}` : 'Not specified'}`
                      : 'Not specified',
                  ],
                  ['Location', [seekerProfile?.city, seekerProfile?.province].filter(Boolean).join(', ') || 'Not specified'],
                ].map(([label, value]) => (
                  <div key={label} className="p-3 rounded-xl bg-slate-50 border border-slate-100">
                    <p className="text-[10px] font-bold text-slate-400 uppercase tracking-wider">{label}</p>
                    <p className="mt-1 text-xs font-semibold text-slate-700">{value}</p>
                  </div>
                ))}
              </div>
            </div>

            {/* Uploaded Resumes & Credentials */}
            <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-4">
              <div className="flex items-center justify-between gap-3">
                <h4 className="text-xs font-bold text-slate-900 flex items-center gap-2">
                  <FileText className="w-4 h-4 text-[#00b074]" /> Uploaded Resumes &amp; Credentials
                </h4>
                <span className="text-[10px] font-semibold text-slate-500">
                  {applicantDocuments.length} {applicantDocuments.length === 1 ? 'document' : 'documents'}
                </span>
              </div>
              {applicantDocuments.length === 0 ? (
                <p className="text-xs text-slate-500">No resumes or credentials have been uploaded.</p>
              ) : (
                <div className="space-y-4">
                  {applicantDocuments.map((doc: any) => {
                    const fileName = doc.file_name?.toLowerCase() || '';
                    const isImage = doc.mime_type?.startsWith('image/') || /\.(jpe?g|png|webp|gif)$/i.test(fileName);
                    const isPdf = doc.mime_type === 'application/pdf' || fileName.endsWith('.pdf');
                    const previewUrl = documentUrls[doc.id];
                    const typeLabel = (doc.document_type || 'document').replace(/_/g, ' ');

                    return (
                      <div key={doc.id} className="rounded-xl border border-slate-200 overflow-hidden">
                        <div className="p-3 flex flex-col sm:flex-row sm:items-center justify-between gap-3 bg-slate-50">
                          <div className="flex items-center gap-2.5 min-w-0">
                            <FileText className="w-5 h-5 text-emerald-700 shrink-0" />
                            <div className="min-w-0">
                              <p className="text-xs font-bold text-slate-900 truncate">{doc.file_name}</p>
                              <p className="text-[10px] text-slate-500 capitalize">
                                {typeLabel}
                                {doc.uploaded_at ? ` · Uploaded ${new Date(doc.uploaded_at).toLocaleDateString()}` : ''}
                                {doc.verification_status ? ` · ${doc.verification_status.replace(/_/g, ' ')}` : ''}
                              </p>
                            </div>
                          </div>
                          <div className="flex items-center gap-2 shrink-0">
                            {previewUrl && (
                              <a
                                href={previewUrl}
                                target="_blank"
                                rel="noopener noreferrer"
                                className="px-3 py-1.5 rounded-lg border border-slate-200 bg-white text-[11px] font-semibold text-slate-700 hover:bg-slate-100"
                              >
                                View / Download
                              </a>
                            )}
                            {isAutoGeneratedResume(doc) && (
                              <Button
                                variant="outline"
                                size="sm"
                                onClick={() => handleDownloadGeneratedResume(doc)}
                                className="font-semibold text-[11px] border-emerald-300 text-emerald-800 hover:bg-emerald-50"
                              >
                                <Download className="w-3.5 h-3.5" /> Download PDF
                              </Button>
                            )}
                          </div>
                        </div>
                        {documentErrors[doc.id] ? (
                          <p className="p-3 text-xs text-rose-700 bg-rose-50">{documentErrors[doc.id]}</p>
                        ) : !previewUrl ? (
                          <p className="p-3 text-xs text-slate-500">Loading secure document preview…</p>
                        ) : isImage ? (
                          <div className="p-3 bg-slate-100 flex justify-center">
                            <img
                              src={previewUrl}
                              alt={`Uploaded ${typeLabel}: ${doc.file_name}`}
                              className="max-h-[32rem] max-w-full object-contain rounded-lg"
                            />
                          </div>
                        ) : isPdf ? (
                          <iframe
                            src={previewUrl}
                            title={`Uploaded ${typeLabel}: ${doc.file_name}`}
                            className="w-full h-[32rem] bg-white"
                          />
                        ) : (
                          <p className="p-3 text-xs text-slate-500">
                            Preview is unavailable for this file type. Use “View / Download” to open it.
                          </p>
                        )}
                      </div>
                    );
                  })}
                </div>
              )}
            </div>

          {/* Skills */}
          <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-3">
            <h4 className="text-xs font-bold text-slate-900 flex items-center gap-2">
              <Sparkles className="w-4 h-4 text-[#00b074]" /> Skills &amp; Proficiencies
            </h4>
            {application.applicant?.skills?.length ? (
              <div className="flex flex-wrap gap-2">
                {application.applicant.skills.map((sk: any) => (
                  <span
                    key={sk.id}
                    className="text-xs font-medium px-3 py-1 rounded-full bg-[#e6f7f0] text-[#008f5d] border border-[#c2edd9]"
                  >
                    {sk.skill?.name || 'Skill'} {sk.proficiency ? `(Lvl ${sk.proficiency}/5)` : ''}
                  </span>
                ))}
              </div>
            ) : (
              <p className="text-xs text-slate-500">No skills have been added.</p>
            )}
          </div>

          {/* Work Experience */}
          <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-3">
            <h4 className="text-xs font-bold text-slate-900 flex items-center gap-2">
              <Briefcase className="w-4 h-4 text-[#00b074]" /> Work Experience
            </h4>
            {application.applicant?.work_experiences?.length ? (
              <div className="space-y-3">
                {application.applicant.work_experiences.map((experience: any) => (
                  <div key={experience.id} className="p-3 bg-slate-50 rounded-xl border border-slate-100">
                    <div className="flex flex-col sm:flex-row sm:items-start sm:justify-between gap-1">
                      <div>
                        <h5 className="text-xs font-bold text-slate-900">{experience.job_title}</h5>
                        <p className="text-[11px] text-slate-600">{experience.company_name}</p>
                      </div>
                      <p className="text-[10px] text-slate-500">
                        {experience.start_date ? new Date(experience.start_date).toLocaleDateString() : 'Start date not specified'}
                        {' – '}
                        {experience.is_current
                          ? 'Present'
                          : experience.end_date
                            ? new Date(experience.end_date).toLocaleDateString()
                            : 'End date not specified'}
                      </p>
                    </div>
                    {experience.description && (
                      <p className="mt-2 text-xs text-slate-600 whitespace-pre-line">{experience.description}</p>
                    )}
                  </div>
                ))}
              </div>
            ) : (
              <p className="text-xs text-slate-500">No work experience has been added.</p>
            )}
          </div>

          {/* Education */}
          <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-3">
            <h4 className="text-xs font-bold text-slate-900 flex items-center gap-2">
              <GraduationCap className="w-4 h-4 text-[#00b074]" /> Education Records
            </h4>
            {application.applicant?.educations?.length ? (
              <div className="space-y-2">
                {application.applicant.educations.map((edu: any) => (
                  <div key={edu.id} className="p-3 bg-slate-50 rounded-xl border border-slate-100">
                    <h5 className="text-xs font-bold text-slate-900">
                      {edu.degree} in {edu.field_of_study}
                    </h5>
                    <p className="text-[11px] text-slate-500">
                      {edu.school_name || edu.institution}
                      {edu.start_date || edu.end_date
                        ? ` (${edu.start_date ? new Date(edu.start_date).getFullYear() : ''} - ${edu.end_date ? new Date(edu.end_date).getFullYear() : 'Present'})`
                        : ''}
                    </p>
                  </div>
                ))}
              </div>
            ) : (
              <p className="text-xs text-slate-500">No education history has been added.</p>
            )}
          </div>

          {/* Certifications */}
          <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-3">
            <h4 className="text-xs font-bold text-slate-900 flex items-center gap-2">
              <Award className="w-4 h-4 text-[#00b074]" /> Certifications
            </h4>
            {application.applicant?.certifications?.length ? (
              <div className="space-y-2">
                {application.applicant.certifications.map((certification: any) => (
                  <div key={certification.id} className="p-3 bg-slate-50 rounded-xl border border-slate-100">
                    <h5 className="text-xs font-bold text-slate-900">{certification.name}</h5>
                    <p className="text-[11px] text-slate-500">
                      {certification.issuer}
                      {certification.issue_date ? ` · Issued ${new Date(certification.issue_date).toLocaleDateString()}` : ''}
                      {certification.expiry_date ? ` · Expires ${new Date(certification.expiry_date).toLocaleDateString()}` : ''}
                    </p>
                    {certification.credential_url && (
                      <a
                        href={certification.credential_url}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="mt-1 inline-block text-[11px] font-semibold text-emerald-700 hover:underline"
                      >
                        View credential
                      </a>
                    )}
                  </div>
                ))}
              </div>
            ) : (
              <p className="text-xs text-slate-500">No certifications have been added.</p>
            )}
          </div>
        </div>

        {/* Right Column: Contact Candidate & Status Management */}
        <div className="lg:col-span-4 space-y-6">
          {/* Direct Contact Box (Phone & Email) */}
          <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-4">
            <h4 className="text-xs font-bold text-slate-900 uppercase tracking-wider">
              Contact Candidate Directly
            </h4>
            <p className="text-xs text-slate-500 leading-relaxed">
              Reach out directly to schedule a discussion or interview via their provided contact details:
            </p>

            <div className="space-y-2.5 pt-1">
              {phone && (
                <a
                  href={`tel:${phone}`}
                  className="w-full py-3 px-4 rounded-xl bg-[#00b074] hover:bg-[#009b66] text-white text-xs font-bold flex items-center justify-center gap-2 shadow-xs transition-all active:scale-[0.99]"
                >
                  <Phone className="w-4 h-4" /> Call: {phone}
                </a>
              )}

              {email && (
                <a
                  href={`mailto:${email}?subject=Application for ${encodeURIComponent(application.job?.title || 'Job Opening')}`}
                  className="w-full py-3 px-4 rounded-xl border border-slate-200 hover:bg-slate-50 text-slate-700 text-xs font-bold flex items-center justify-center gap-2 transition-colors truncate"
                >
                  <Mail className="w-4 h-4 text-blue-600 shrink-0" />
                  <span className="truncate">Email Candidate</span>
                </a>
              )}
            </div>
          </div>

          {/* Status Management */}
          <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-4">
            <div className="flex items-center justify-between">
              <h4 className="text-xs font-bold text-slate-900 uppercase tracking-wider">
                Application Status
              </h4>
              <span className={`text-[10px] font-semibold px-2 py-0.5 rounded-full border ${currentStatusObj.color}`}>
                {currentStatusObj.label}
              </span>
            </div>

            {statusLocked ? (
              <p className="text-xs font-semibold text-rose-700 bg-rose-50 border border-rose-200 rounded-xl p-3">
                {hiredElsewhere
                  ? 'This candidate has already accepted an offer elsewhere. Their application status is locked.'
                  : 'This hire is confirmed. The application status is locked.'}
              </p>
            ) : (
              <>
                <p className="text-xs text-slate-500">
                  Click below to immediately update the status visible to the candidate:
                </p>

                <div className="space-y-2">
                  {STATUS_OPTIONS.map((stg) => {
                    const isActive = application.status === stg.value;
                    return (
                      <button
                        key={stg.value}
                        type="button"
                        disabled={isUpdating}
                        onClick={() => handleStatusChange(stg.value)}
                        className={`w-full py-2.5 px-3.5 rounded-xl text-xs font-bold transition-all flex items-center justify-between border cursor-pointer ${
                          isActive
                            ? 'bg-[#00b074] text-white border-[#00b074] shadow-xs'
                            : 'bg-white border-slate-200 text-slate-700 hover:bg-slate-50'
                        }`}
                      >
                        <span>{stg.label}</span>
                        {isActive && <Check className="w-4 h-4 text-white" />}
                      </button>
                    );
                  })}
                </div>
              </>
            )}
          </div>
        </div>
      </div>
    </DashboardLayout>
  );
}
