'use client';

import React, { useState, useEffect, useRef } from 'react';
import Link from 'next/link';
import { Navbar } from '@/components/layout/Navbar';
import { Footer } from '@/components/layout/Footer';
import { ResumeGeneratorModal } from '@/components/seeker/ResumeGeneratorModal';
import { supabase } from '@/lib/supabase/client';
import { calculateProfileCompleteness, formatCurrency } from '@/lib/utils';
import {
  saveAutoGeneratedResume,
  uploadResumeFile,
  downloadDocument,
  isAutoGeneratedResume,
} from '@/lib/services/resumeService';
import {
  MapPin,
  Mail,
  Phone,
  Share2,
  Edit2,
  User,
  Sparkles,
  GraduationCap,
  Award,
  CheckCircle2,
  Calendar,
  FileCheck,
  Check,
  Clock,
  Briefcase,
  UploadCloud,
  FileText,
  Download,
  Trash2,
  Plus,
  DollarSign,
  Compass,
  Laptop,
  AlertCircle,
  Eye,
  Loader2,
} from 'lucide-react';

const CERT_COLORS = ['bg-blue-600', 'bg-amber-500', 'bg-emerald-600', 'bg-purple-600', 'bg-indigo-600'];

export default function SeekerProfilePage() {
  const [userId, setUserId] = useState<string>('');
  const [profile, setProfile] = useState<any>(null);
  const [seekerProfile, setSeekerProfile] = useState<any>(null);
  const [skills, setSkills] = useState<any[]>([]);
  const [educations, setEducations] = useState<any[]>([]);
  const [experiences, setExperiences] = useState<any[]>([]);
  const [documents, setDocuments] = useState<any[]>([]);
  const [recentApplications, setRecentApplications] = useState<any[]>([]);
  const [stats, setStats] = useState({ applied: 0, saved: 0, reviewed: 0 });
  const [copiedShare, setCopiedShare] = useState(false);
  const [loading, setLoading] = useState(true);

  // Resume Modal & Upload State
  const [isResumeModalOpen, setIsResumeModalOpen] = useState(false);
  const [uploadingResume, setUploadingResume] = useState(false);
  const [generatingResume, setGeneratingResume] = useState(false);
  const [resumeActionSuccess, setResumeActionSuccess] = useState('');
  const [resumeActionError, setResumeActionError] = useState('');
  const resumeFileInputRef = useRef<HTMLInputElement>(null);

  // Custom delete confirmation modal state
  const [deleteConfirm, setDeleteConfirm] = useState<{ id: string; filePath?: string; name: string } | null>(null);
  const [deletingDoc, setDeletingDoc] = useState(false);

  useEffect(() => {
    supabase.auth.getUser().then(({ data: { user } }) => {
      if (!user) return;
      setUserId(user.id);
      fetchProfileData(user.id, user);
    });
  }, []);

  async function fetchProfileData(uid: string, authUser: any) {
    const [
      profileRes,
      seekerRes,
      skillsRes,
      eduRes,
      expRes,
      docsRes,
      appsRes,
      savedRes,
    ] = await Promise.all([
      supabase.from('profiles').select('*').eq('id', uid).maybeSingle(),
      supabase.from('job_seeker_profiles').select('*').eq('user_id', uid).maybeSingle(),
      supabase.from('job_seeker_skills').select('*, skill:skills(*)').eq('user_id', uid),
      supabase.from('educations').select('*').eq('user_id', uid).order('start_date', { ascending: false }),
      supabase.from('work_experiences').select('*').eq('user_id', uid).order('start_date', { ascending: false }),
      supabase.from('documents').select('*').eq('user_id', uid).order('uploaded_at', { ascending: false }),
      supabase
        .from('applications')
        .select('*, job:jobs(title, company:companies(name))')
        .eq('applicant_id', uid)
        .order('applied_at', { ascending: false }),
      supabase.from('saved_jobs').select('id').eq('user_id', uid),
    ]);

    const meta = authUser.user_metadata;
    const fallbackFirst =
      meta?.first_name ||
      meta?.full_name?.split(' ')[0] ||
      meta?.name?.split(' ')[0] ||
      authUser.email?.split('@')[0] ||
      '';
    const fallbackLast =
      meta?.last_name ||
      meta?.full_name?.split(' ').slice(1).join(' ') ||
      meta?.name?.split(' ').slice(1).join(' ') ||
      '';

    const pData = profileRes.data || {
      first_name: fallbackFirst,
      last_name: fallbackLast,
      email: authUser.email,
      phone: '',
      avatar_url: meta?.avatar_url || meta?.picture || null,
    };

    setProfile(pData);
    setSeekerProfile(seekerRes.data);
    setSkills(skillsRes.data ?? []);
    setEducations(eduRes.data ?? []);
    setExperiences(expRes.data ?? []);
    setDocuments(docsRes.data ?? []);

    const apps = appsRes.data ?? [];
    setRecentApplications(apps.slice(0, 4));
    setStats({
      applied: apps.length,
      saved: (savedRes.data ?? []).length,
      reviewed: apps.filter((a: any) => a.status === 'screening' || a.status === 'hired').length,
    });

    setLoading(false);
  }

  // Refresh only documents after resume operations
  async function refreshDocuments() {
    if (!userId) return;
    const { data } = await supabase
      .from('documents')
      .select('*')
      .eq('user_id', userId)
      .order('uploaded_at', { ascending: false });
    setDocuments(data ?? []);
  }

  const getInitials = () => {
    if (!profile) return 'WM';
    const firstInitial = profile.first_name?.[0] || '';
    const lastInitial = profile.last_name?.[0] || '';
    return (firstInitial + lastInitial).toUpperCase() || 'WM';
  };

  const handleShare = () => {
    if (typeof window !== 'undefined') {
      navigator.clipboard.writeText(window.location.href);
      setCopiedShare(true);
      setTimeout(() => setCopiedShare(false), 2500);
    }
  };

  // Status mapping for simple human-friendly display
  const getStatusBadge = (status?: string) => {
    switch (status) {
      case 'hired':
        return { label: 'Contacted', color: 'text-[#00b074] bg-emerald-50 border-emerald-200' };
      case 'screening':
        return { label: 'Under Review', color: 'text-blue-600 bg-blue-50 border-blue-200' };
      case 'rejected':
        return { label: 'Rejected', color: 'text-rose-600 bg-rose-50 border-rose-200' };
      case 'applied':
      default:
        return { label: 'Pending', color: 'text-amber-600 bg-amber-50 border-amber-200' };
    }
  };

  // Upload Resume File from profile
  const handleResumeFileUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file || !userId) return;

    setUploadingResume(true);
    setResumeActionError('');
    setResumeActionSuccess('');

    try {
      await uploadResumeFile(userId, file);
      await refreshDocuments();
      setResumeActionSuccess(`Resume "${file.name}" uploaded successfully!`);
      setTimeout(() => setResumeActionSuccess(''), 4000);
    } catch (err: any) {
      console.error('Resume upload error:', err);
      setResumeActionError(err.message || 'Failed to upload resume file.');
    } finally {
      setUploadingResume(false);
      if (resumeFileInputRef.current) {
        resumeFileInputRef.current.value = '';
      }
    }
  };

  // Quick 1-Click Instant Auto-Generate Resume
  const handleInstantAutoGenerate = async () => {
    if (!userId) return;
    setGeneratingResume(true);
    setResumeActionError('');
    setResumeActionSuccess('');

    try {
      await saveAutoGeneratedResume(userId, {
        profile,
        seekerProfile,
        skills,
        educations,
        experiences,
      });
      await refreshDocuments();
      setResumeActionSuccess('Auto-generated resume created and saved to your profile!');
      setTimeout(() => setResumeActionSuccess(''), 4000);
    } catch (err: any) {
      console.error('Instant generate error:', err);
      setResumeActionError(err.message || 'Failed to auto-generate resume.');
    } finally {
      setGeneratingResume(false);
    }
  };

  // Delete a resume document — triggered AFTER custom modal confirm
  const confirmDeleteDocument = async () => {
    if (!deleteConfirm) return;
    setDeletingDoc(true);
    try {
      if (deleteConfirm.filePath) {
        await supabase.storage.from('documents').remove([deleteConfirm.filePath]);
      }
      await supabase.from('documents').delete().eq('id', deleteConfirm.id);
      await refreshDocuments();
      setResumeActionSuccess('Resume removed from your profile.');
      setTimeout(() => setResumeActionSuccess(''), 3500);
    } catch (err: any) {
      console.error('Error deleting document:', err);
      setResumeActionError('Failed to remove resume. Please try again.');
      setTimeout(() => setResumeActionError(''), 4000);
    } finally {
      setDeletingDoc(false);
      setDeleteConfirm(null);
    }
  };

  if (loading) {
    return (
      <div className="min-h-screen flex flex-col bg-[#f8fafc]">
        <Navbar />
        <main className="flex-1 flex items-center justify-center p-12">
          <div className="w-9 h-9 border-3 border-[#00b074] border-t-transparent rounded-full animate-spin" />
        </main>
        <Footer />
      </div>
    );
  }

  // Profile data values reflecting all edits
  const fullName = `${profile?.first_name || ''} ${profile?.last_name || ''}`.trim() || 'WorkMatch Candidate';
  const headline = seekerProfile?.professional_title || 'Candidate Profile';
  const location = [seekerProfile?.city, seekerProfile?.province].filter(Boolean).join(', ') || 'Philippines';
  const email = profile?.email || '';
  const phone = profile?.phone || '';
  const bio = seekerProfile?.bio || '';

  // Filter resumes
  const resumeDocs = documents.filter((d) => d.document_type === 'resume');

  // Completion calculation (using real experiences!)
  const completeness = Math.min(
    100,
    calculateProfileCompleteness(seekerProfile, skills, educations, experiences, documents)
  );

  return (
    <div className="min-h-screen flex flex-col bg-[#f8fafc] text-slate-800 selection:bg-emerald-200">
      <Navbar />

      {/* ─── Custom Delete Confirmation Modal ──────────────────────── */}
      {deleteConfirm && (
        <div
          className="fixed inset-0 z-[100] flex items-center justify-center p-4"
          style={{ background: 'rgba(15,23,42,0.55)', backdropFilter: 'blur(4px)' }}
        >
          <div
            className="bg-white rounded-2xl shadow-2xl w-full max-w-sm p-6 flex flex-col gap-4"
            style={{ animation: 'fadeScaleIn 0.2s ease' }}
          >
            {/* Icon */}
            <div className="w-14 h-14 rounded-full bg-rose-50 border border-rose-100 flex items-center justify-center mx-auto">
              <Trash2 className="w-6 h-6 text-rose-500" strokeWidth={2.5} />
            </div>

            {/* Text */}
            <div className="text-center">
              <h3 className="text-lg font-bold text-slate-900 mb-1">Delete Resume?</h3>
              <p className="text-sm text-slate-500 leading-relaxed">
                Are you sure you want to remove{' '}
                <span className="font-semibold text-slate-700">&ldquo;{deleteConfirm.name}&rdquo;</span>{' '}
                from your profile? This cannot be undone.
              </p>
            </div>

            {/* Actions */}
            <div className="flex gap-3 mt-1">
              <button
                onClick={() => setDeleteConfirm(null)}
                disabled={deletingDoc}
                className="flex-1 px-4 py-2.5 rounded-xl border border-slate-200 text-slate-700 font-semibold text-sm hover:bg-slate-50 transition-colors disabled:opacity-50"
              >
                Cancel
              </button>
              <button
                onClick={confirmDeleteDocument}
                disabled={deletingDoc}
                className="flex-1 px-4 py-2.5 rounded-xl bg-rose-500 hover:bg-rose-600 text-white font-semibold text-sm transition-colors flex items-center justify-center gap-2 disabled:opacity-60"
              >
                {deletingDoc ? (
                  <Loader2 className="w-4 h-4 animate-spin" />
                ) : (
                  <Trash2 className="w-4 h-4" />
                )}
                {deletingDoc ? 'Deleting…' : 'Delete'}
              </button>
            </div>
          </div>
          <style>{`@keyframes fadeScaleIn { from { opacity:0; transform:scale(.92); } to { opacity:1; transform:scale(1); } }`}</style>
        </div>
      )}

      {/* ─── Hero Emerald Banner ─────────────────────────────────── */}
      <div className="h-44 sm:h-52 w-full bg-[#0c4a34] bg-gradient-to-r from-[#03442e] via-[#097b53] to-[#03442e] relative shadow-inner" />

      {/* ─── Profile Header Overlapping Banner ───────────────────── */}
      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 w-full -mt-20 relative z-10">
        <div className="bg-white rounded-3xl border border-slate-200/90 p-6 sm:p-8 shadow-xs flex flex-col lg:flex-row items-start lg:items-center justify-between gap-6">
          {/* Avatar + Main Details */}
          <div className="flex flex-col sm:flex-row items-start sm:items-center gap-5 min-w-0 flex-1">
            {/* Avatar with Online Dot */}
            <div className="relative shrink-0">
              <div className="w-24 h-24 sm:w-28 sm:h-28 rounded-full border-4 border-white bg-[#00b074] text-white font-black text-2xl sm:text-3xl flex items-center justify-center shadow-md overflow-hidden">
                {profile?.avatar_url ? (
                  <img
                    src={profile.avatar_url}
                    alt={fullName}
                    className="w-full h-full object-cover"
                  />
                ) : (
                  getInitials()
                )}
              </div>
              {/* Online Dot */}
              <span
                className="w-5 h-5 rounded-full bg-emerald-500 border-3 border-white absolute bottom-1 right-1 shadow-xs"
                title="Active Candidate"
              />
            </div>

            {/* Name + Title + Contact Row */}
            <div className="space-y-1.5 min-w-0">
              <div className="flex flex-wrap items-center gap-2">
                <h1 className="text-2xl sm:text-3xl font-black text-slate-900 tracking-tight">
                  {fullName}
                </h1>
                {seekerProfile?.availability && (
                  <span className="text-[11px] font-bold px-2.5 py-0.5 rounded-full bg-emerald-50 text-emerald-700 border border-emerald-200">
                    {seekerProfile.availability}
                  </span>
                )}
              </div>
              <p className="text-xs sm:text-sm font-semibold text-slate-600">
                {headline}
              </p>

              <div className="flex flex-wrap items-center gap-y-1 gap-x-4 text-xs text-slate-500 pt-1">
                {location && (
                  <span className="flex items-center gap-1.5">
                    <MapPin className="w-3.5 h-3.5 text-slate-400" />
                    {location}
                  </span>
                )}
                {email && (
                  <span className="flex items-center gap-1.5">
                    <Mail className="w-3.5 h-3.5 text-slate-400" />
                    {email}
                  </span>
                )}
                {phone && (
                  <span className="flex items-center gap-1.5">
                    <Phone className="w-3.5 h-3.5 text-slate-400" />
                    {phone}
                  </span>
                )}
              </div>
            </div>
          </div>

          {/* Action Buttons: Auto-Generate Resume, Share Profile & Edit Profile */}
          <div className="flex flex-wrap items-center gap-2.5 shrink-0 self-end lg:self-center">
            <button
              type="button"
              onClick={() => setIsResumeModalOpen(true)}
              className="px-4 py-2.5 rounded-xl border border-emerald-200 bg-emerald-50 hover:bg-emerald-100 text-[#008f5d] text-xs font-bold flex items-center gap-1.5 shadow-2xs transition-all active:scale-95 cursor-pointer"
            >
              <Sparkles className="w-3.5 h-3.5 text-[#00b074]" /> Auto-Generate Resume
            </button>

            <button
              type="button"
              onClick={handleShare}
              className="px-4 py-2.5 rounded-xl border border-slate-200 bg-white hover:bg-slate-50 text-slate-700 text-xs font-semibold flex items-center gap-1.5 shadow-2xs transition-colors cursor-pointer"
            >
              {copiedShare ? (
                <>
                  <Check className="w-3.5 h-3.5 text-[#00b074]" /> Copied!
                </>
              ) : (
                <>
                  <Share2 className="w-3.5 h-3.5 text-slate-500" /> Share Profile
                </>
              )}
            </button>

            <Link
              href="/seeker/profile/edit"
              className="px-5 py-2.5 rounded-xl bg-[#00b074] hover:bg-[#009b66] text-white text-xs font-bold flex items-center gap-1.5 shadow-sm transition-all active:scale-95"
            >
              <Edit2 className="w-3.5 h-3.5" /> Edit Profile
            </Link>
          </div>
        </div>

        {/* ─── Career Preferences Strip (Reflecting Edit Profile Fields) ───── */}
        <div className="mt-4 bg-white rounded-2xl border border-slate-200/90 p-4 shadow-xs grid grid-cols-2 sm:grid-cols-4 gap-3 text-xs">
          <div className="flex items-center gap-2.5 p-2 rounded-xl bg-slate-50/70 border border-slate-100">
            <Briefcase className="w-4 h-4 text-emerald-600 shrink-0" />
            <div>
              <p className="text-[10px] text-slate-400 font-semibold uppercase">Experience</p>
              <p className="text-xs font-bold text-slate-800">
                {seekerProfile?.years_experience
                  ? `${seekerProfile.years_experience} Years`
                  : '1 Year'}
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2.5 p-2 rounded-xl bg-slate-50/70 border border-slate-100">
            <Laptop className="w-4 h-4 text-blue-600 shrink-0" />
            <div>
              <p className="text-[10px] text-slate-400 font-semibold uppercase">Work Arrangement</p>
              <p className="text-xs font-bold text-slate-800">
                {seekerProfile?.preferred_work_arrangement || 'Hybrid'}
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2.5 p-2 rounded-xl bg-slate-50/70 border border-slate-100">
            <Compass className="w-4 h-4 text-purple-600 shrink-0" />
            <div>
              <p className="text-[10px] text-slate-400 font-semibold uppercase">Job Type</p>
              <p className="text-xs font-bold text-slate-800">
                {seekerProfile?.preferred_job_type || 'Full-time'}
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2.5 p-2 rounded-xl bg-slate-50/70 border border-slate-100">
            <DollarSign className="w-4 h-4 text-amber-600 shrink-0" />
            <div>
              <p className="text-[10px] text-slate-400 font-semibold uppercase">Expected Salary</p>
              <p className="text-xs font-bold text-slate-800">
                {seekerProfile?.preferred_salary_min
                  ? `${formatCurrency(seekerProfile.preferred_salary_min)} / mo`
                  : 'Competitive'}
              </p>
            </div>
          </div>
        </div>
      </div>

      {/* ─── Main 2-Column Content ─────────────────────────────────── */}
      <main className="flex-1 max-w-7xl mx-auto w-full px-4 sm:px-6 lg:px-8 py-8">
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-8 items-start">

          {/* ─── LEFT COLUMN (8 cols): Bio, Resumes, Experience, Skills, Education ──────── */}
          <div className="lg:col-span-8 space-y-6">

            {/* Notification messages for Resume actions */}
            {resumeActionSuccess && (
              <div className="bg-emerald-50 border border-emerald-200 text-emerald-800 text-xs p-3.5 rounded-2xl flex items-center gap-2 animate-in fade-in">
                <CheckCircle2 className="w-4 h-4 text-[#00b074] shrink-0" />
                <span>{resumeActionSuccess}</span>
              </div>
            )}
            {resumeActionError && (
              <div className="bg-rose-50 border border-rose-200 text-rose-800 text-xs p-3.5 rounded-2xl flex items-center gap-2 animate-in fade-in">
                <AlertCircle className="w-4 h-4 text-rose-600 shrink-0" />
                <span>{resumeActionError}</span>
              </div>
            )}

            {/* 1. Resume Management Card (Upload Resume & Auto-Generate Resume) */}
            <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-4">
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-slate-100">
                <div>
                  <h2 className="text-sm font-bold text-slate-900 flex items-center gap-2">
                    <FileText className="w-4 h-4 text-[#00b074]" /> Resumes &amp; Documents
                  </h2>
                  <p className="text-[11px] text-slate-500 mt-0.5">
                    Upload an existing resume file or auto-generate one directly from your profile.
                  </p>
                </div>

                <div className="flex items-center gap-2 shrink-0">
                  {/* Hidden File Input */}
                  <input
                    ref={resumeFileInputRef}
                    type="file"
                    accept=".pdf,.doc,.docx,.jpg,.jpeg,.png"
                    onChange={handleResumeFileUpload}
                    className="hidden"
                  />
                  <button
                    type="button"
                    onClick={() => resumeFileInputRef.current?.click()}
                    disabled={uploadingResume}
                    className="px-3.5 py-2 rounded-xl border border-slate-200 bg-white hover:bg-slate-50 text-slate-700 text-xs font-semibold flex items-center gap-1.5 shadow-2xs transition-colors cursor-pointer disabled:opacity-50"
                  >
                    {uploadingResume ? (
                      <>
                        <Loader2 className="w-3.5 h-3.5 animate-spin text-[#00b074]" /> Uploading...
                      </>
                    ) : (
                      <>
                        <UploadCloud className="w-3.5 h-3.5 text-slate-500" /> Upload Resume
                      </>
                    )}
                  </button>

                  <button
                    type="button"
                    onClick={handleInstantAutoGenerate}
                    disabled={generatingResume}
                    className="px-3.5 py-2 rounded-xl bg-[#00b074] hover:bg-[#009b66] text-white text-xs font-bold flex items-center gap-1.5 shadow-xs transition-all active:scale-95 cursor-pointer disabled:opacity-50"
                  >
                    {generatingResume ? (
                      <>
                        <Loader2 className="w-3.5 h-3.5 animate-spin text-white" /> Generating...
                      </>
                    ) : (
                      <>
                        <Sparkles className="w-3.5 h-3.5" /> Auto-Generate
                      </>
                    )}
                  </button>
                </div>
              </div>

              {/* List of Resumes on file */}
              {resumeDocs.length === 0 ? (
                <div className="border-2 border-dashed border-slate-200 rounded-2xl p-6 text-center space-y-3 bg-slate-50/50">
                  <div className="w-12 h-12 rounded-full bg-emerald-50 text-emerald-600 flex items-center justify-center mx-auto">
                    <FileText className="w-6 h-6" />
                  </div>
                  <div className="space-y-1">
                    <p className="text-xs font-bold text-slate-800">No Resume Attached Yet</p>
                    <p className="text-[11px] text-slate-500 max-w-sm mx-auto">
                      Having an active resume on your profile makes applying to jobs 10x faster and increases your employer response rate.
                    </p>
                  </div>
                  <div className="flex items-center justify-center gap-2.5 pt-1">
                    <button
                      type="button"
                      onClick={() => resumeFileInputRef.current?.click()}
                      className="px-4 py-2 rounded-xl bg-white border border-slate-200 text-xs font-semibold text-slate-700 hover:bg-slate-50 flex items-center gap-1.5 shadow-2xs cursor-pointer"
                    >
                      <UploadCloud className="w-3.5 h-3.5 text-[#00b074]" /> Upload File (PDF/DOCX)
                    </button>
                    <button
                      type="button"
                      onClick={() => setIsResumeModalOpen(true)}
                      className="px-4 py-2 rounded-xl bg-emerald-50 border border-emerald-200 text-xs font-bold text-[#008f5d] hover:bg-emerald-100 flex items-center gap-1.5 cursor-pointer"
                    >
                      <Sparkles className="w-3.5 h-3.5" /> Build with AI Resume Maker
                    </button>
                  </div>
                </div>
              ) : (
                <div className="space-y-2.5">
                  {resumeDocs.map((doc) => {
                    const isGenerated = isAutoGeneratedResume(doc);
                    return (
                      <div
                        key={doc.id}
                        className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 p-3.5 rounded-xl border border-slate-200/80 bg-white hover:border-emerald-300 transition-all shadow-2xs"
                      >
                        <div className="flex items-center gap-3 min-w-0">
                          <div
                            className={`w-10 h-10 rounded-xl flex items-center justify-center shrink-0 ${
                              isGenerated
                                ? 'bg-emerald-100/70 text-emerald-700 border border-emerald-200'
                                : 'bg-blue-50 text-blue-600 border border-blue-100'
                            }`}
                          >
                            {isGenerated ? (
                              <Sparkles className="w-5 h-5" />
                            ) : (
                              <FileText className="w-5 h-5" />
                            )}
                          </div>
                          <div className="min-w-0">
                            <div className="flex items-center gap-2">
                              <h4 className="text-xs font-bold text-slate-900 truncate">
                                {doc.file_name}
                              </h4>
                              {isGenerated ? (
                                <span className="text-[10px] font-extrabold px-2 py-0.5 rounded-full bg-emerald-50 text-emerald-700 border border-emerald-200 shrink-0">
                                  ⚡ Auto-Generated
                                </span>
                              ) : (
                                <span className="text-[10px] font-semibold px-2 py-0.5 rounded-full bg-slate-100 text-slate-600 border border-slate-200 shrink-0">
                                  📁 Uploaded
                                </span>
                              )}
                            </div>
                            <p className="text-[10px] text-slate-400 mt-0.5">
                              Uploaded{' '}
                              {doc.uploaded_at
                                ? new Date(doc.uploaded_at).toLocaleDateString('en-US', {
                                    month: 'short',
                                    day: 'numeric',
                                    year: 'numeric',
                                  })
                                : 'Recently'}{' '}
                              • {doc.file_size ? `${(doc.file_size / 1024).toFixed(1)} KB` : 'Document'}
                            </p>
                          </div>
                        </div>

                        <div className="flex items-center gap-1.5 shrink-0 self-end sm:self-center">
                          {isGenerated && (
                            <button
                              type="button"
                              onClick={() => setIsResumeModalOpen(true)}
                              className="px-2.5 py-1.5 rounded-lg border border-emerald-200 bg-emerald-50 hover:bg-emerald-100 text-[#008f5d] text-xs font-semibold flex items-center gap-1 cursor-pointer"
                              title="Open Resume Customizer & Live Preview"
                            >
                              <Eye className="w-3.5 h-3.5" /> Preview
                            </button>
                          )}
                          <button
                            type="button"
                            onClick={() =>
                              downloadDocument(
                                doc,
                                doc.file_name,
                                {
                                  profile,
                                  seekerProfile,
                                  skills,
                                  educations,
                                  experiences,
                                },
                                userId
                              )
                            }
                            className="px-3 py-1.5 rounded-lg border border-slate-200 bg-white hover:bg-slate-50 text-slate-700 text-xs font-semibold flex items-center gap-1 shadow-2xs cursor-pointer"
                            title="Download Resume"
                          >
                            <Download className="w-3.5 h-3.5 text-slate-500" /> Download
                          </button>
                          <button
                            type="button"
                            onClick={() => setDeleteConfirm({ id: doc.id, filePath: doc.file_path, name: doc.file_name })}
                            className="p-1.5 rounded-lg border border-slate-200 text-slate-400 hover:text-rose-600 hover:bg-rose-50 transition-colors cursor-pointer"
                            title="Delete resume"
                          >
                            <Trash2 className="w-3.5 h-3.5" />
                          </button>
                        </div>
                      </div>
                    );
                  })}
                </div>
              )}
            </div>

            {/* 2. About Me Card */}
            <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-3">
              <div className="flex items-center justify-between">
                <h2 className="text-sm font-bold text-slate-900 flex items-center gap-2">
                  <User className="w-4 h-4 text-[#00b074]" /> About Me
                </h2>
                <Link
                  href="/seeker/profile/edit"
                  className="text-xs font-semibold text-[#00b074] hover:underline flex items-center gap-1"
                >
                  <Edit2 className="w-3 h-3" /> Edit
                </Link>
              </div>
              {bio ? (
                <p className="text-xs sm:text-sm text-slate-600 leading-relaxed font-normal whitespace-pre-line">
                  {bio}
                </p>
              ) : (
                <p className="text-xs text-slate-400 italic">
                  No summary added yet. Click &quot;Edit&quot; to write a brief bio about your career, goals, and passions.
                </p>
              )}
            </div>

            {/* 3. Work Experience Card (Directly reflects Edit Profile) */}
            <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-4">
              <div className="flex items-center justify-between">
                <h2 className="text-sm font-bold text-slate-900 flex items-center gap-2">
                  <Briefcase className="w-4 h-4 text-[#00b074]" /> Work Experience
                </h2>
                <Link
                  href="/seeker/profile/edit"
                  className="text-xs font-semibold text-[#00b074] hover:underline flex items-center gap-1"
                >
                  <Plus className="w-3 h-3" /> Add Experience
                </Link>
              </div>

              {experiences.length === 0 ? (
                <div className="p-4 rounded-xl border border-dashed border-slate-200 bg-slate-50/50 text-center space-y-2">
                  <Briefcase className="w-6 h-6 text-slate-300 mx-auto" />
                  <p className="text-xs text-slate-500 font-medium">No work experience listed yet.</p>
                  <Link
                    href="/seeker/profile/edit"
                    className="inline-block text-xs font-bold text-[#00b074] hover:underline"
                  >
                    + Add your work history in Edit Profile
                  </Link>
                </div>
              ) : (
                <div className="space-y-4 pt-1">
                  {experiences.map((exp, idx) => (
                    <div
                      key={exp.id || idx}
                      className="p-4 rounded-xl border border-slate-100 bg-slate-50/40 space-y-2 hover:border-slate-200 transition-all"
                    >
                      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-1">
                        <div>
                          <h4 className="text-xs sm:text-sm font-bold text-slate-900">
                            {exp.job_title}
                          </h4>
                          <p className="text-xs text-slate-600 font-medium">{exp.company_name}</p>
                        </div>
                        <span className="text-[11px] font-semibold text-slate-400 flex items-center gap-1">
                          <Calendar className="w-3 h-3 text-slate-400" />
                          {exp.start_date || 'Start'} – {exp.is_current ? 'Present' : exp.end_date || 'Present'}
                        </span>
                      </div>
                      {exp.description && (
                        <p className="text-xs text-slate-500 leading-relaxed font-normal whitespace-pre-line pt-1">
                          {exp.description}
                        </p>
                      )}
                    </div>
                  ))}
                </div>
              )}
            </div>

            {/* 4. My Skills Card (Directly reflects Edit Profile) */}
            <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-4">
              <div className="flex items-center justify-between">
                <h2 className="text-sm font-bold text-slate-900 flex items-center gap-2">
                  <Sparkles className="w-4 h-4 text-[#00b074]" /> My Skills
                </h2>
                <Link
                  href="/seeker/profile/edit"
                  className="text-xs font-semibold text-[#00b074] hover:underline flex items-center gap-1"
                >
                  <Edit2 className="w-3 h-3" /> Edit Skills
                </Link>
              </div>

              {skills.length === 0 ? (
                <div className="p-4 rounded-xl border border-dashed border-slate-200 bg-slate-50/50 text-center space-y-2">
                  <Sparkles className="w-6 h-6 text-slate-300 mx-auto" />
                  <p className="text-xs text-slate-500 font-medium">No skills added yet.</p>
                  <Link
                    href="/seeker/profile/edit"
                    className="inline-block text-xs font-bold text-[#00b074] hover:underline"
                  >
                    + Add skills in Edit Profile
                  </Link>
                </div>
              ) : (
                <div className="flex flex-wrap items-center gap-2 pt-1">
                  {skills.map((s, sIdx) => {
                    const skillName = s.skill?.name || s.name || 'Skill';
                    const prof = s.proficiency || 3;
                    return (
                      <span
                        key={s.id || sIdx}
                        className="inline-flex items-center gap-1.5 text-xs font-medium px-3.5 py-1.5 rounded-full bg-[#e6f7f0] text-[#008f5d] border border-[#c2edd9] transition-colors"
                      >
                        <span>{skillName}</span>
                        <span className="text-[10px] font-bold text-[#00b074] bg-white px-1.5 py-0.2 rounded-full border border-emerald-200">
                          lvl {prof}
                        </span>
                      </span>
                    );
                  })}
                </div>
              )}
            </div>

            {/* 5. Education & Credentials Card (Directly reflects Edit Profile) */}
            <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-4">
              <div className="flex items-center justify-between">
                <h2 className="text-sm font-bold text-slate-900 flex items-center gap-2">
                  <GraduationCap className="w-4 h-4 text-[#00b074]" /> Education &amp; Credentials
                </h2>
                <Link
                  href="/seeker/profile/edit"
                  className="text-xs font-semibold text-[#00b074] hover:underline flex items-center gap-1"
                >
                  <Plus className="w-3 h-3" /> Add Education
                </Link>
              </div>

              {educations.length === 0 ? (
                <div className="p-4 rounded-xl border border-dashed border-slate-200 bg-slate-50/50 text-center space-y-2">
                  <GraduationCap className="w-6 h-6 text-slate-300 mx-auto" />
                  <p className="text-xs text-slate-500 font-medium">No education history added yet.</p>
                  <Link
                    href="/seeker/profile/edit"
                    className="inline-block text-xs font-bold text-[#00b074] hover:underline"
                  >
                    + Add education in Edit Profile
                  </Link>
                </div>
              ) : (
                <div className="space-y-3 pt-1">
                  {educations.map((item, idx) => {
                    const school = item.school_name || item.institution || 'Institution';
                    const degree = item.degree || 'Degree';
                    const field = item.field_of_study ? ` - ${item.field_of_study}` : '';
                    const period =
                      item.start_year || item.end_year
                        ? `${item.start_year || ''} - ${item.end_year || 'Present'}`
                        : item.start_date
                        ? `${new Date(item.start_date).getFullYear()} - ${
                            item.end_date ? new Date(item.end_date).getFullYear() : 'Present'
                          }`
                        : '';
                    const color = CERT_COLORS[idx % CERT_COLORS.length];

                    return (
                      <div
                        key={item.id || idx}
                        className="flex items-center justify-between gap-4 p-3.5 rounded-xl border border-slate-100 hover:border-slate-200 bg-slate-50/40 hover:bg-slate-50/80 transition-all"
                      >
                        <div className="flex items-center gap-3.5 min-w-0">
                          <div
                            className={`w-10 h-10 rounded-xl ${color} text-white flex items-center justify-center shrink-0 shadow-2xs`}
                          >
                            <Award className="w-5 h-5 text-white" />
                          </div>

                          <div className="min-w-0">
                            <h4 className="text-xs font-bold text-slate-900 truncate">
                              {degree}{field}
                            </h4>
                            <p className="text-[11px] text-slate-500 truncate">{school}</p>
                            {period && <p className="text-[10px] text-slate-400">{period}</p>}
                          </div>
                        </div>

                        <span className="inline-flex items-center gap-1 text-[10px] font-semibold text-[#00b074] bg-emerald-50 px-2.5 py-0.5 rounded-full border border-emerald-200/60 shrink-0">
                          <CheckCircle2 className="w-3 h-3 text-[#00b074]" /> Verified
                        </span>
                      </div>
                    );
                  })}
                </div>
              )}
            </div>
          </div>

          {/* ─── RIGHT COLUMN (4 cols): Completion, Applications ───── */}
          <div className="lg:col-span-4 space-y-6">

            {/* Profile Completion Card */}
            <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-5">
              <div className="flex items-center justify-between">
                <span className="text-xs font-bold text-slate-800">
                  Profile Completion
                </span>
                <span className="text-base font-black text-[#00b074]">
                  {completeness}%
                </span>
              </div>

              {/* Progress bar */}
              <div className="w-full h-2 bg-slate-100 rounded-full overflow-hidden">
                <div
                  className="h-full bg-[#00b074] rounded-full transition-all duration-500"
                  style={{ width: `${completeness}%` }}
                />
              </div>

              {/* Stats Row */}
              <div className="grid grid-cols-3 gap-2 text-center py-2 border-y border-slate-100">
                <div className="space-y-0.5">
                  <div className="text-base font-black text-slate-900">
                    {stats.applied}
                  </div>
                  <div className="text-[10px] font-semibold text-slate-400">
                    Applied
                  </div>
                </div>

                <div className="space-y-0.5 border-x border-slate-100">
                  <div className="text-base font-black text-slate-900">
                    {stats.saved}
                  </div>
                  <div className="text-[10px] font-semibold text-slate-400">
                    Saved
                  </div>
                </div>

                <div className="space-y-0.5">
                  <div className="text-base font-black text-slate-900">
                    {stats.reviewed}
                  </div>
                  <div className="text-[10px] font-semibold text-slate-400">
                    Reviewed
                  </div>
                </div>
              </div>

              {/* View Certificates / Upload Diploma Button */}
              <Link
                href="/seeker/diploma"
                className="w-full py-3 rounded-xl bg-[#00b074] hover:bg-[#009b66] text-white text-xs font-bold flex items-center justify-center gap-2 shadow-sm transition-all active:scale-[0.99]"
              >
                <FileCheck className="w-4 h-4" /> View Certificates &amp; Diplomas
              </Link>
            </div>

            {/* Recent Applications Card */}
            <div className="bg-white rounded-2xl border border-slate-200/90 p-6 shadow-xs space-y-4">
              <h3 className="text-xs font-bold text-slate-900 flex items-center gap-2">
                <Calendar className="w-4 h-4 text-[#00b074]" /> Recent Applications
              </h3>

              {recentApplications.length === 0 ? (
                <div className="text-center py-6 space-y-2">
                  <Briefcase className="w-8 h-8 text-slate-300 mx-auto" />
                  <p className="text-xs text-slate-500 font-medium">No applications yet</p>
                  <Link
                    href="/jobs"
                    className="inline-block text-xs font-semibold text-[#00b074] hover:underline"
                  >
                    Browse open roles →
                  </Link>
                </div>
              ) : (
                <div className="space-y-3">
                  {recentApplications.map((app) => {
                    const statusInfo = getStatusBadge(app.status);
                    return (
                      <div
                        key={app.id}
                        className="flex items-center justify-between gap-3 p-3 rounded-xl border border-slate-100 hover:border-slate-200 bg-slate-50/30 transition-all"
                      >
                        <div className="space-y-0.5 min-w-0">
                          <h4 className="text-xs font-bold text-slate-900 truncate">
                            {app.job?.title || 'Position'}
                          </h4>
                          <p className="text-[11px] text-slate-500 truncate">
                            {app.job?.company?.name || 'Company'}
                          </p>
                          <p className="text-[10px] text-slate-400 flex items-center gap-1">
                            <Clock className="w-3 h-3 text-slate-300" />
                            {app.applied_at
                              ? new Date(app.applied_at).toLocaleDateString('en-US', {
                                  month: 'short',
                                  day: 'numeric',
                                  year: 'numeric',
                                })
                              : 'Recent'}
                          </p>
                        </div>

                        {/* Status Label */}
                        <span
                          className={`text-[10px] font-semibold px-2.5 py-0.5 rounded-full border ${statusInfo.color} shrink-0`}
                        >
                          {statusInfo.label}
                        </span>
                      </div>
                    );
                  })}
                </div>
              )}
            </div>
          </div>
        </div>
      </main>

      {/* ─── Resume Generator Modal ─────────────────────────────────── */}
      <ResumeGeneratorModal
        isOpen={isResumeModalOpen}
        onClose={() => setIsResumeModalOpen(false)}
        profile={profile}
        seekerProfile={seekerProfile}
        skills={skills}
        educations={educations}
        experiences={experiences}
        documents={documents}
        onDocumentSaved={refreshDocuments}
      />

      <Footer />
    </div>
  );
}
