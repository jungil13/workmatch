import { supabase } from '@/lib/supabase/client';

export interface ResumeDataInput {
  profile: any;
  seekerProfile: any;
  skills: any[];
  educations: any[];
  experiences: any[];
}

/**
 * Generate formatted text representation of a candidate's resume
 */
export function generateResumePlainText(data: ResumeDataInput): string {
  const { profile, seekerProfile, skills = [], educations = [], experiences = [] } = data;

  const fullName = `${profile?.first_name || ''} ${profile?.last_name || ''}`.trim() || 'WorkMatch Candidate';
  const title = seekerProfile?.professional_title || 'Professional Candidate';
  const location = [seekerProfile?.city, seekerProfile?.province].filter(Boolean).join(', ') || 'Philippines';
  const email = profile?.email || '';
  const phone = profile?.phone || '';
  const bio = seekerProfile?.bio || '';

  let text = `======================================================================\n`;
  text += `${fullName.toUpperCase()}\n`;
  text += `${title}\n`;
  text += `${location} | ${email}${phone ? ` | ${phone}` : ''}\n`;
  text += `======================================================================\n\n`;

  // Career Preferences
  const prefParts = [];
  if (seekerProfile?.availability) prefParts.push(`Availability: ${seekerProfile.availability}`);
  if (seekerProfile?.preferred_work_arrangement) prefParts.push(`Arrangement: ${seekerProfile.preferred_work_arrangement}`);
  if (seekerProfile?.preferred_job_type) prefParts.push(`Job Type: ${seekerProfile.preferred_job_type}`);
  if (seekerProfile?.years_experience) prefParts.push(`Experience: ${seekerProfile.years_experience} Years`);
  if (prefParts.length > 0) {
    text += `CAREER PREFERENCES\n`;
    text += `--------------------------------------------------\n`;
    text += prefParts.join('  •  ') + `\n\n`;
  }

  // Professional Summary
  if (bio) {
    text += `PROFESSIONAL SUMMARY\n`;
    text += `--------------------------------------------------\n`;
    text += `${bio}\n\n`;
  }

  // Work Experiences
  if (experiences.length > 0) {
    text += `WORK EXPERIENCE\n`;
    text += `--------------------------------------------------\n`;
    experiences.forEach((exp) => {
      text += `${exp.job_title} | ${exp.company_name}\n`;
      const start = exp.start_date || '';
      const end = exp.is_current ? 'Present' : exp.end_date || 'Present';
      text += `Period: ${start} – ${end}\n`;
      if (exp.description) {
        text += `${exp.description}\n`;
      }
      text += `\n`;
    });
  }

  // Education
  if (educations.length > 0) {
    text += `EDUCATION & CREDENTIALS\n`;
    text += `--------------------------------------------------\n`;
    educations.forEach((edu) => {
      const degree = edu.degree || 'Degree';
      const field = edu.field_of_study ? ` in ${edu.field_of_study}` : '';
      const school = edu.school_name || edu.institution || 'Educational Institution';
      const startYear = edu.start_year || (edu.start_date ? new Date(edu.start_date).getFullYear() : '');
      const endYear = edu.end_year || (edu.end_date ? new Date(edu.end_date).getFullYear() : 'Present');
      const period = startYear || endYear ? ` (${startYear || ''} – ${endYear || ''})` : '';

      text += `${degree}${field}\n`;
      text += `${school}${period}\n\n`;
    });
  }

  // Skills
  if (skills.length > 0) {
    text += `CORE SKILLS & COMPETENCIES\n`;
    text += `--------------------------------------------------\n`;
    const skillList = skills
      .map((s) => {
        const name = s.skill?.name || s.name || 'Skill';
        const prof = s.proficiency ? ` (Proficiency: ${s.proficiency}/5)` : '';
        return `${name}${prof}`;
      })
      .join(', ');
    text += `${skillList}\n\n`;
  }

  text += `======================================================================\n`;
  text += `Verified WorkMatch Candidate Profile • Generated on ${new Date().toLocaleDateString('en-US', {
    month: 'long',
    day: 'numeric',
    year: 'numeric',
  })}\n`;
  text += `======================================================================\n`;

  return text;
}

/**
 * Check if a document record is an auto-generated resume
 */
export function isAutoGeneratedResume(doc: any): boolean {
  if (!doc) return false;
  const notes = (doc.verification_notes || '').toLowerCase();
  const name = (doc.file_name || '').toLowerCase();
  const path = (doc.file_path || '').toLowerCase();

  return (
    notes.includes('auto-generated') ||
    notes.includes('generated from workmatch') ||
    notes.includes('generated and verified') ||
    name.includes('generated_resume') ||
    path.includes('generated')
  );
}

/**
 * Save an auto-generated resume directly to storage and documents table
 */
export async function saveAutoGeneratedResume(userId: string, data: ResumeDataInput) {
  const textContent = generateResumePlainText(data);
  const blob = new Blob([textContent], { type: 'text/plain;charset=utf-8' });

  const safeName = `${data.profile?.first_name || 'Candidate'}_${data.profile?.last_name || 'Resume'}`.replace(
    /[^a-zA-Z0-9_-]/g,
    '_'
  );
  const fileName = `${safeName}_Generated_Resume.txt`;
  const storagePath = `resumes/${userId}/${Date.now()}_${fileName}`;

  // 1. Upload to Supabase Storage
  const { error: uploadError } = await supabase.storage
    .from('documents')
    .upload(storagePath, blob, {
      cacheControl: '3600',
      upsert: true,
      contentType: 'text/plain',
    });

  if (uploadError) {
    console.warn('Resume storage upload warning:', uploadError.message);
  }

  // 2. Insert into documents table
  const { data: docData, error: dbError } = await supabase
    .from('documents')
    .insert({
      user_id: userId,
      document_type: 'resume',
      file_name: fileName,
      file_path: storagePath,
      file_size: blob.size,
      mime_type: 'text/plain',
      verification_status: 'verified',
      verification_notes: 'Auto-generated from WorkMatch profile data',
      uploaded_at: new Date().toISOString(),
      verified_at: new Date().toISOString(),
    })
    .select()
    .single();

  if (dbError) throw dbError;
  return docData;
}

/**
 * Upload a candidate resume file directly to storage and documents table
 */
export async function uploadResumeFile(userId: string, file: File) {
  const sanitized = file.name.replace(/[^a-zA-Z0-9._-]/g, '_');
  const storagePath = `resumes/${userId}/${Date.now()}_${sanitized}`;

  const { error: uploadError } = await supabase.storage
    .from('documents')
    .upload(storagePath, file, {
      cacheControl: '3600',
      upsert: true,
      contentType: file.type || 'application/octet-stream',
    });

  if (uploadError) {
    console.warn('Storage upload warning:', uploadError.message);
  }

  const { data: docData, error: dbError } = await supabase
    .from('documents')
    .insert({
      user_id: userId,
      document_type: 'resume',
      file_name: file.name,
      file_path: storagePath,
      mime_type: file.type || 'application/pdf',
      file_size: file.size,
      verification_status: 'verified',
      verification_notes: 'Candidate uploaded resume',
      uploaded_at: new Date().toISOString(),
      verified_at: new Date().toISOString(),
    })
    .select()
    .single();

  if (dbError) throw dbError;
  return docData;
}

/**
 * Download a document file or open in new tab
 */
export async function downloadDocument(filePath: string, fileName?: string) {
  try {
    // 1. Try signed URL first
    const { data, error } = await supabase.storage.from('documents').createSignedUrl(filePath, 3600);
    if (!error && data?.signedUrl) {
      window.open(data.signedUrl, '_blank');
      return;
    }

    // 2. Fallback to public URL
    const { data: pubData } = supabase.storage.from('documents').getPublicUrl(filePath);
    if (pubData?.publicUrl) {
      window.open(pubData.publicUrl, '_blank');
      return;
    }

    throw new Error('Unable to generate download URL');
  } catch (err) {
    console.error('Download document error:', err);
    alert('Failed to download document. Please try again.');
  }
}
